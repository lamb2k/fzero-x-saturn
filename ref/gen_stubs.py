#!/usr/bin/env python3
"""Generate link stubs for the reference harness (card G1.2).

Every symbol the compiled closure needs but does not define gets a stub:
- functions (called through a PC-relative relocation) become no-ops that count their calls;
  the harness reports every stub that ran, so a run shows which OUT code the simulation
  actually touched, and a stub that should have been compiled stands out;
- data become zeroed, aligned storage.

Usage: gen_stubs.py OUT.c OBJECT...
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

DATA_BYTES = 0x10000
# Real libc/libm functions: never stubbed. glibc sqrtf is correctly rounded, like VR4300 sqrt.s.
LIBC = {"sqrtf", "sqrt", "sinf", "cosf", "fabsf", "bzero", "bcopy", "bcmp", "memcpy", "memset",
        "memmove", "memcmp", "sprintf", "printf", "fprintf", "strlen", "strcmp", "strcpy",
        "fopen", "fclose", "fread", "fgets", "fgetc", "sscanf", "strtol", "strchr", "fputs",
        "fwrite", "putchar", "puts", "abort", "exit", "malloc", "free", "stderr", "stdout"}


def symbols(objects: list[str]) -> tuple[set[str], set[str]]:
    defined, undefined = set(), set()
    out = subprocess.run(["nm", *objects], capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == "U":
            undefined.add(parts[1])
        elif len(parts) == 3 and parts[1] in "TtDdBbRrCcVvWw":
            defined.add(parts[2])
    return defined, undefined - defined


def called(objects: list[str]) -> set[str]:
    out = subprocess.run(["objdump", "-r", *objects], capture_output=True, text=True,
                         check=True).stdout
    names = set()
    for line in out.splitlines():
        m = re.match(r"^[0-9a-f]+\s+(R_386_PC32|R_386_PLT32)\s+(\S+)", line)
        if m:
            names.add(m.group(2))
    return names


def main() -> int:
    out, objects = Path(sys.argv[1]), sys.argv[2:]
    _defined, missing = symbols(objects)
    calls = called(objects)
    missing = {n for n in missing - LIBC if not n.startswith("ref_stub_")}
    functions = sorted(n for n in missing if n in calls and (not n.startswith("__") or n.startswith("__os")))
    data = sorted(n for n in missing if n not in calls and (not n.startswith("__") or n.startswith("__os"))
                  and not n.startswith("_GLOBAL_OFFSET_TABLE_"))
    lines = [
        "/* Generated by ref/gen_stubs.py. Do not edit. */",
        "#include <stdint.h>",
        "#include \"ref_stubs.h\"",
        f"#define REF_STUB_COUNT {len(functions)}",
        "const char *const ref_stub_names[REF_STUB_COUNT] = {",
        *(f'    "{n}",' for n in functions),
        "};",
        "uint32_t ref_stub_calls[REF_STUB_COUNT];",
        "const uint32_t ref_stub_count = REF_STUB_COUNT;",
    ]
    for i, n in enumerate(functions):
        lines.append(f"int {n}() {{ ++ref_stub_calls[{i}]; return 0; }}")
    for n in data:
        lines.append(f"__attribute__((aligned(16))) unsigned char {n}[{DATA_BYTES:#x}];")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"stubs: {len(functions)} functions, {len(data)} data symbols")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
