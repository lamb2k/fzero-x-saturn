#!/usr/bin/env python3
"""Generate build/stubs.c for every symbol the reference objects need but nothing defines.

A symbol reached by a call becomes a function that does nothing and returns
zero, typed float when the decomp declares it returning f32 or f64 (i386
returns floats on the x87 stack, so an untyped stub would corrupt it). Any
other symbol becomes zeroed storage. Prints a census of what was stubbed.

Usage: gen_stubs.py OUT.c PREPROCESSED.i... -- OBJECT.o...
"""
import os
import re
import subprocess
import sys

# Bytes of zeroed storage per data stand-in. REF_STUB_SIZE shrinks it (ref/sat/build.sh proves
# on the host that the shrunk size leaves every fixture hash unchanged).
STUB_SIZE = int(os.environ.get("REF_STUB_SIZE", "0x40000"), 0)
# REF_STUB_SIZES names a file of "symbol bytes" lines that overrides the size per symbol.
SIZES = {}
if os.environ.get("REF_STUB_SIZES"):
    for _line in open(os.environ["REF_STUB_SIZES"]):
        _f = _line.split()
        if len(_f) == 2:
            SIZES[_f[0]] = int(_f[1], 0)


def main(argv):
    out, rest = argv[1], argv[2:]
    sep = rest.index("--")
    texts = [open(p, encoding="utf-8", errors="replace").read() for p in rest[:sep]]
    objects = rest[sep + 1:]
    nm = subprocess.run(["nm", *objects], check=True, capture_output=True, text=True).stdout
    defined, undefined = set(), set()
    for line in nm.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == "U":
            undefined.add(parts[1])
        elif len(parts) == 3:
            defined.add(parts[2])
    # The host C library supplies memcpy, sqrtf and friends: never stub those (a zero sqrtf would
    # silently change the physics). Ask the compiler where its 32-bit libc and libm are.
    host = set()
    for lib in ("libc.so.6", "libm.so.6"):
        path = subprocess.run(["gcc", "-m32", f"-print-file-name={lib}"], capture_output=True, text=True).stdout.strip()
        dyn = subprocess.run(["nm", "-D", "--defined-only", path], capture_output=True, text=True).stdout
        host |= {parts[-1].split("@")[0] for parts in (l.split() for l in dyn.splitlines()) if len(parts) >= 3}
    if not {"memcpy", "sqrtf"} <= host:
        raise SystemExit("gen_stubs: cannot read the host libc/libm symbol tables")
    need = sorted(undefined - defined - host)
    print("host library calls used by the decomp: " + " ".join(sorted((undefined - defined) & host)))
    relocs = subprocess.run(["objdump", "-dr", *objects], check=True, capture_output=True, text=True).stdout
    called = set(re.findall(r"call\s+\S+\s*\n\s+\S+:\s+R_386_(?:PC32|PLT32)\s+(\w+)", relocs))
    called |= set(re.findall(r"R_386_(?:PC32|PLT32)\s+(\w+)", relocs))
    text = "\n".join(texts)
    funcs = data = floats = 0
    datas = []
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* Generated by ref/gen_stubs.py; regenerate, never edit. */\n")
        for name in need:
            if name in called:
                if re.search(rf"\b(f32|f64|float|double)\s*\**\s*\b{re.escape(name)}\s*\(", text):
                    fh.write(f"float {name}(void) {{ return 0.0f; }}\n")
                    floats += 1
                else:
                    fh.write(f"int {name}(void) {{ return 0; }}\n")
                funcs += 1
            else:
                fh.write(f"unsigned char {name}[0x{SIZES.get(name, STUB_SIZE):X}] __attribute__((aligned(64)));\n")
                datas.append(name)
                data += 1
        # Extent report for ref/sat: the highest non-zero byte each data stand-in holds at exit
        # (main.c calls it when REF_STUB_REPORT names a file). Sizes the SH-2 stand-ins.
        fh.write("#include <stdio.h>\nstatic const struct { const char* n; const unsigned char* p; long size; } ref_stub_table[] = {\n")
        for name in datas:
            fh.write(f'    {{ "{name}", {name}, 0x{SIZES.get(name, STUB_SIZE):X} }},\n')
        fh.write("};\nvoid ref_stub_report(const char* path) {\n"
                 "    FILE* f = fopen(path, \"a\");\n    unsigned i;\n    if (!f) return;\n"
                 "    for (i = 0; i < sizeof(ref_stub_table) / sizeof(ref_stub_table[0]); i++) {\n"
                 "        long k = ref_stub_table[i].size - 1;\n"
                 "        while (k >= 0 && ref_stub_table[i].p[k] == 0) k--;\n"
                 "        fprintf(f, \"%s %ld\\n\", ref_stub_table[i].n, k + 1);\n    }\n    fclose(f);\n}\n")
    print(f"stubs: {funcs} functions ({floats} returning float), {data} data symbols")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
