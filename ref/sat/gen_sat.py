#!/usr/bin/env python3
"""Write the data side of the reference-on-SH-2 probe.

    gen_sat.py OUT_DIR SCRIPT.txt HOST_STUBS_C

OUT_DIR/sat_data.c: the synthetic fixture course record (big-endian, from fixture_course.py)
and the input script as an array. OUT_DIR/sat_stubs.c and sat_stubs_data.s: the stand-ins of
the host stubs file given (same sources, so the same undefined symbols), which ref/sat/build.sh
generated with per-symbol sizes measured on the host and proved there to keep every hash.
Function stand-ins stay C; data stand-ins get the same sizes at fixed low-work-RAM addresses.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BUTTONS = {"A": 0x8000, "B": 0x4000, "Z": 0x2000, "S": 0x1000, "L": 0x0020, "R": 0x0010,
           "CU": 0x0008, "CD": 0x0004, "CL": 0x0002, "CR": 0x0001}


def main():
    out, script, host_stubs = sys.argv[1:4]
    os.makedirs(out, exist_ok=True)
    course = os.path.join(out, "course.bin")
    subprocess.run([sys.executable, os.path.join(HERE, "..", "fixture_course.py"), course], check=True)
    record = open(course, "rb").read()
    assert len(record) == 0x7E0
    steps = []
    for line in open(script):
        f = line.split()
        if not f or f[0].startswith("#"):
            continue
        mask = 0
        if f[1] != "-":
            for b in f[1].split("+"):
                mask |= BUTTONS[b]
        sx = int(f[2]) if len(f) > 2 else 0
        sy = int(f[3]) if len(f) > 3 else 0
        steps.append((int(f[0]), mask, sx, sy))
    name = os.path.splitext(os.path.basename(script))[0]
    with open(os.path.join(out, "sat_data.c"), "w", newline="\n") as fh:
        fh.write("/* Generated by ref/sat/gen_sat.py; regenerate, never edit. Synthetic fixture only. */\n")
        fh.write("const char sat_script_name[] = \"%s\";\n" % name)
        fh.write("const unsigned char sat_course_record[%d] = {\n" % len(record))
        for i in range(0, len(record), 16):
            fh.write("    " + ", ".join("0x%02X" % b for b in record[i:i + 16]) + ",\n")
        fh.write("};\n")
        fh.write("typedef struct { unsigned short ticks; unsigned short button; signed char sx, sy; } SatStep;\n")
        fh.write("const SatStep sat_steps[] = {\n")
        for t, m, sx, sy in steps:
            fh.write("    { %d, 0x%04X, %d, %d },\n" % (t, m, sx, sy))
        fh.write("};\nconst unsigned int sat_step_count = %d;\n" % len(steps))
    # Function stand-ins stay C. Data stand-ins become fixed addresses in low work RAM
    # (0x00200000, 1 MB, otherwise unused by the probe); main_sat.c zeroes that range first.
    funcs, datas = [], []
    for line in open(host_stubs):
        m = re.match(r"unsigned char (\w+)\[(0x[0-9A-Fa-f]+)\]", line)
        if m:
            datas.append((m.group(1), int(m.group(2), 16)))
        elif re.match(r"(int|float) \w+\(void\)", line):
            funcs.append(line)
    addr, layout = 0x00200000, []
    for name, size in datas:
        layout.append((name, addr))
        addr += (size + 63) & ~63
    if addr > 0x00300000:
        sys.exit("data stand-ins do not fit in low work RAM")
    with open(os.path.join(out, "sat_stubs.c"), "w", newline="\n") as fh:
        fh.write("/* Generated by ref/sat/gen_sat.py from the host stubs; never edit. */\n")
        fh.writelines(funcs)
    with open(os.path.join(out, "sat_stubs_data.s"), "w", newline="\n") as fh:
        fh.write("! Generated by ref/sat/gen_sat.py: data stand-ins in low work RAM.\n")
        for name, a in layout:
            fh.write("\t.global _%s\n\t.set _%s, 0x%08X\n" % (name, name, a))
        fh.write("\t.global _sat_stub_data_end\n\t.set _sat_stub_data_end, 0x%08X\n" % addr)


if __name__ == "__main__":
    main()
