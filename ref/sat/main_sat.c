/* Reference-on-SH-2 probe (G1.3 cross-check): the original race code, compiled for the
 * Saturn's master SH-2 with soft-float binary32, stepped through one fixture input script.
 * MIT; see ../../LICENSE.
 *
 * It hashes the same per-tick values as ref/main.c in the same little-endian byte order, so
 * the final hash must equal the host reference's hash for that script (STRICT). Each tick is
 * timed with the free-running timer (master clock / 32). Results go to the screen and to
 * `fzx_sat_result`, which tools/emu/yaba_boot.ps1 or the MCP memory_read tool can read.
 * Timings from an emulator are MODELLED. */
#include <yaul.h>

#include <stdint.h>
#include <string.h>

#include "../ref.h"

/* Generated by ref/sat/gen_sat.py: the course record and the input script. */
extern const unsigned char sat_course_record[REF_COURSE_RECORD_SIZE];
typedef struct {
    uint16_t ticks;
    uint16_t button;
    int8_t sx, sy;
} SatStep;
extern const SatStep sat_steps[];
extern const uint32_t sat_step_count;
extern const char sat_script_name[];
extern unsigned char sat_stub_data_end[];

#define MAX_TICKS 4096

typedef struct {
    uint32_t magic;      /* 'FZXR' once done */
    uint32_t state;      /* 0 running, 1 done, 2 init failed */
    uint32_t ticks;
    uint32_t hash_hi, hash_lo;
    uint32_t frt_sum;    /* sum of per-tick FRT counts (each count = 32 master cycles) */
    uint32_t frt_max;
    uint32_t frt_max_tick;
    uint32_t frt_race_sum, race_ticks; /* ticks after the intro (intro == 0) */
    uint32_t frt_race_max;
#if FZX_SOURCE_CAMERA
    uint32_t camera_hash, camera_faults, camera_count;
#endif
} SatResult;

SatResult fzx_sat_result;
#if FZX_SOURCE_CAMERA
uint32_t fzx_sat_frt[MAX_TICKS];
#else
uint16_t fzx_sat_frt[MAX_TICKS];
#endif
/* Debug window: the race state right after init and after each of the first 16 ticks. */
int32_t fzx_sat_init_intro;
/* The probe waits up to 600 fields for a debugger (MCP memory_write) to set this non-zero,
 * so breakpoints and the CPU core can be chosen before the race is initialised. */
volatile uint32_t fzx_sat_go;
RefState fzx_sat_states[16];

#if FZX_SOURCE_CAMERA
static volatile uint32_t timer_high;
static void timer_overflow(void) { timer_high += 65536u; }
static uint32_t timer_now(void) {
    volatile cpu_ioregs_t* const io=(volatile cpu_ioregs_t*)CPU_IOREG_BASE;
    const uint32_t mask=cpu_intc_mask_get();
    uint32_t value;
    uint8_t before, after, high, low, high2;
    cpu_intc_mask_set(15);
    /* OVF can be pending before the handler extends the timer. Read both
     * the pending flag and the bytewise counter coherently under the mask. */
    do {
        before=io->ftcsr&2u;
        high=io->frch; low=io->frcl; high2=io->frch;
        after=io->ftcsr&2u;
    } while(before!=after || high!=high2);
    value=timer_high+(after ? 65536u : 0u)+((uint32_t)high<<8)+low;
    cpu_intc_mask_set(mask);
    return value;
}
static uint32_t camera_hash = 2166136261u;
RefCamera fzx_sat_camera[2];
uint32_t fzx_sat_camera_blocks[MAX_TICKS/64];
static void camera_word(uint32_t word) {
    unsigned int i;
    for (i=0; i<4; ++i) { camera_hash=(camera_hash^(uint8_t)word)*16777619u; word>>=8; }
}
static void mix_camera(uint32_t tick) {
    unsigned int i,j;
    const unsigned int count=ref_camera_count();
    fzx_sat_result.camera_count=count;
    if(count!=2) { ++fzx_sat_result.camera_faults; return; }
    for(i=0;i<count;++i) {
        RefCamera* c=&fzx_sat_camera[i];
        if(!ref_camera_read(i,c)) { ++fzx_sat_result.camera_faults; return; }
        camera_word(tick); camera_word(i);
        for(j=0;j<sizeof(*c)/4;++j) {
            uint32_t word;
            memcpy(&word,(const unsigned char*)c+4*j,4);
            if(j>=4 && j<62 && (word&0x7F800000u)==0x7F800000u) ++fzx_sat_result.camera_faults;
            camera_word(word);
        }
        fzx_sat_result.camera_faults+=c->faults;
    }
    if((tick&63)==63) fzx_sat_camera_blocks[tick/64]=camera_hash;
}
#endif

static uint64_t hash = 0xCBF29CE484222325ull;

static void mix_byte(uint8_t b) {
    hash = (hash ^ b) * 0x100000001B3ull;
}

/* ref/main.c mixes host (little-endian) memory: reproduce those bytes. */
static void mix_le(uint32_t v, int size) {
    int i;
    for (i = 0; i < size; i++) {
        mix_byte((uint8_t) (v >> (8 * i)));
    }
}

static uint32_t fbits(float f) {
    uint32_t u;
    memcpy(&u, &f, 4);
    return u;
}

static void mix_state(int tick, const SatStep* in) {
    RefState s;
    int i;

    ref_state(&s);
    mix_le((uint32_t) tick, 4);
    mix_le(in->button, 2);
    mix_le((uint8_t) in->sx, 1);
    mix_le((uint8_t) in->sy, 1);
    /* RefState is 18 four-byte fields with no padding, in declaration order. */
    _Static_assert(sizeof(RefState) == 18 * 4, "RefState layout");
    mix_le((uint32_t) s.intro, 4);
    for (i = 0; i < 3; i++) mix_le(fbits(s.pos[i]), 4);
    for (i = 0; i < 3; i++) mix_le(fbits(s.vel[i]), 4);
    mix_le(fbits(s.speed), 4);
    mix_le(fbits(s.energy), 4);
    mix_le(fbits(s.lap_distance), 4);
    mix_le(fbits(s.seg_t), 4);
    mix_le(fbits(s.height), 4);
    mix_le((uint32_t) s.segment, 4);
    mix_le((uint32_t) s.lap, 4);
    mix_le((uint32_t) s.laps_completed, 4);
    mix_le((uint32_t) s.race_time, 4);
    mix_le((uint32_t) s.state_flags, 4);
    mix_le((uint32_t) s.boost_timer, 4);
}

void user_init(void) {
    vdp2_tvmd_display_res_set(VDP2_TVMD_INTERLACE_NONE, VDP2_TVMD_HORZ_NORMAL_A, VDP2_TVMD_VERT_224);
    vdp2_scrn_back_color_set(VDP2_VRAM_ADDR(3, 0x01FFFE), RGB1555(1, 0, 3, 8));
    vdp2_tvmd_display_set();
}

int main(void) {
    SatResult* r = &fzx_sat_result;
    uint32_t i, t, tick = 0;

    dbgio_init();
    dbgio_dev_default_init(DBGIO_DEV_VDP2_ASYNC);
    dbgio_dev_font_load();
    dbgio_printf("\x1b[H\x1b[2J REF ON SH-2 (SOFT FLOAT)\n SCRIPT %s\n RUNNING...\n", sat_script_name);
    dbgio_flush();
    vdp2_sync();
    vdp2_sync_wait();

    for (i = 0; i < 600 && fzx_sat_go == 0; i++) {
        vdp2_sync();
        vdp2_sync_wait();
    }
    memset(r, 0, sizeof(*r));
    /* The decomp's unresolved data symbols live at fixed low-work-RAM addresses (zeroed, as
     * the host's zeroed stubs are). */
    memset((void*) 0x00200000, 0, (size_t) ((uintptr_t) sat_stub_data_end - 0x00200000));
    ref_set_rom_boot(NULL);
    if (ref_load_course(sat_course_record, 1) != 0 || ref_race_init() != 0) {
        r->state = 2;
        r->magic = 0x465A5852;
        dbgio_printf(" INIT FAILED\n");
        dbgio_flush();
        vdp2_sync();
        for (;;) {
        }
    }

    {
        RefState s0;
        ref_state(&s0);
        fzx_sat_init_intro = s0.intro;
    }
    cpu_frt_init(CPU_FRT_CLOCK_DIV_32);
#if FZX_SOURCE_CAMERA
    cpu_intc_mask_set(0);
    cpu_frt_ovi_set(timer_overflow);
    cpu_frt_interrupt_priority_set(12);
#endif
    for (i = 0; i < sat_step_count; i++) {
        for (t = 0; t < sat_steps[i].ticks && tick < MAX_TICKS; t++) {
            RefState s;
#if FZX_SOURCE_CAMERA
            uint32_t c, start=timer_now();
#else
            uint16_t c;
            cpu_frt_count_set(0);
#endif
            ref_tick(sat_steps[i].button, sat_steps[i].sx, sat_steps[i].sy);
#if FZX_SOURCE_CAMERA
            c = timer_now()-start;
#else
            c = cpu_frt_count_get();
#endif
            fzx_sat_frt[tick] = c;
            r->frt_sum += c;
            if (c > r->frt_max) {
                r->frt_max = c;
                r->frt_max_tick = tick;
            }
            mix_state((int) tick, &sat_steps[i]);
#if FZX_SOURCE_CAMERA
            mix_camera(tick);
#endif
            ref_state(&s);
            if (tick < 16) fzx_sat_states[tick] = s;
            if (s.intro == 0) {
                r->frt_race_sum += c;
                r->race_ticks++;
                if (c > r->frt_race_max) r->frt_race_max = c;
            }
            tick++;
        }
    }
    r->ticks = tick;
    r->hash_hi = (uint32_t) (hash >> 32);
    r->hash_lo = (uint32_t) hash;
#if FZX_SOURCE_CAMERA
    r->camera_hash=camera_hash;
    if(r->camera_faults) r->state=3;
    else r->state=1;
#else
    r->state = 1;
#endif
    r->magic = 0x465A5852;

    dbgio_printf(" TICKS %lu\n HASH %08lx%08lx\n", (unsigned long) tick, (unsigned long) r->hash_hi,
                 (unsigned long) r->hash_lo);
    dbgio_printf(" FRT/32 MEAN %lu MAX %lu\n RACE MEAN %lu MAX %lu\n DONE\n",
                 (unsigned long) (r->frt_sum / (tick ? tick : 1)), (unsigned long) r->frt_max,
                 (unsigned long) (r->frt_race_sum / (r->race_ticks ? r->race_ticks : 1)),
                 (unsigned long) r->frt_race_max);
    dbgio_flush();
    vdp2_sync();
    vdp2_sync_wait();
    for (;;) {
        vdp2_sync();
        vdp2_sync_wait();
    }
    return 0;
}
