/* Engine CD audio (ENG_CDDA). The disc holds each music piece as one CD audio track: the intro
 * once, then the loop body repeated past a race's length (tools/bgm_cdda.py). Playback:
 *   1. Play Disc from the track start to its end, no repeat (intro and the repeated body);
 *   2. when the drive stops at the end, Play Disc over [loop-back sector, track end] with
 *      repeat forever. The loop-back sector's phase matches the track end (bgm_cdda.py).
 * The SH-2 only sends commands; the drive streams the audio into the SCSP's CD input.
 * Commands are raw CR1..CR4 writes gated on CMOK, never waited on in the frame loop.
 * Method and register use follow the AvP Saturn audio library (sat_audio.c). */
#include <yaul.h>
#include <string.h>

#include "engine_cdda.h"
#include "cdda_tracks.h"   /* generated by tools/disc_cdda.py; git-ignored, local only */

#define SCSP_RAM ((volatile uint16_t *)0x25A00000u)
#define SCSP_SLOT(n, r) (*(volatile uint16_t *)(0x25B00000u + 0x20u * (n) + (r)))
#define SCSP_COMMON (*(volatile uint16_t *)0x25B00400u)
#define CD_HIRQ (*(volatile uint16_t *)0x25890008u)
#define CD_CR1 (*(volatile uint16_t *)0x25890018u)
#define CD_CR2 (*(volatile uint16_t *)0x2589001Cu)
#define CD_CR3 (*(volatile uint16_t *)0x25890020u)
#define CD_CR4 (*(volatile uint16_t *)0x25890024u)
#define CD_DATA ((volatile const uint32_t *)0x25818000u)
#define HIRQ_CMOK 0x0001u
#define HIRQ_DRDY 0x0002u
#define CD_STATUS_PAUSE 0x01u
#define CD_STATUS_STANDBY 0x02u
#define CD_STATUS_PLAY 0x03u
#define FAD_FLAG 0x800000u
#define PLAY_REPEAT_FOREVER 0x0Fu
#define CD_LEVEL 7u                 /* EFSDL 0..7: full level for the CD input */
#define TOC_TIMEOUT_TICKS 3000000u  /* > 3 s at FRT master/32 */

volatile engine_cdda_stats_t engine_cdda_stats;

static uint16_t pending[4];
static uint8_t want;
static uint32_t loop_fad, loop_sectors;
static uint8_t seen_play;

void engine_cdda_power(void) {
    smpc_smc_sndoff_call();
    SCSP_RAM[0] = 0x0007u; SCSP_RAM[1] = 0xFFFCu;   /* 68000 reset vector: stack */
    SCSP_RAM[2] = 0x0000u; SCSP_RAM[3] = 0x0010u;   /* pc */
    SCSP_RAM[8] = 0x60FEu;                          /* bra.s to itself: the 68000 idles */
    smpc_smc_sndon_call();
    SCSP_COMMON = 0x0200u | 0x000Fu;                /* 4 Mbit sound RAM, master volume full */
    for (unsigned n = 0; n < 32u; ++n)
        for (unsigned r = 0; r < 0x18u; r += 2u) SCSP_SLOT(n, r) = 0;
    SCSP_SLOT(0, 0) = 0x1000u;                      /* key execute: apply the cleared slots */
    SCSP_SLOT(16, 0x16) = (uint16_t)(CD_LEVEL << 5 | 0x1Fu); /* CD left input, hard left */
    SCSP_SLOT(17, 0x16) = (uint16_t)(CD_LEVEL << 5 | 0x0Fu); /* CD right input, hard right */
}

static void command(uint32_t start, uint32_t mode, uint32_t end) {
    pending[0] = (uint16_t)(0x1000u | ((start >> 16) & 0xFFu));   /* Play Disc */
    pending[1] = (uint16_t)start;
    pending[2] = (uint16_t)(mode << 8 | ((end >> 16) & 0xFFu));
    pending[3] = (uint16_t)end;
    want = 1;
}

static void send(void) {
    if (!want) return;
    if (!(CD_HIRQ & HIRQ_CMOK)) { ++engine_cdda_stats.busy_frames; return; }
    CD_HIRQ = (uint16_t)~HIRQ_CMOK;
    CD_CR1 = pending[0]; CD_CR2 = pending[1]; CD_CR3 = pending[2]; CD_CR4 = pending[3];
    want = 0;
    ++engine_cdda_stats.commands;
}

static const fzx_cdda_track_t *find(uint32_t music_id) {
    for (unsigned i = 0; i < FZX_CDDA_TRACK_COUNT; ++i)
        if (fzx_cdda_tracks[i].music_id == music_id) return &fzx_cdda_tracks[i];
    return NULL;
}

static int fail(uint32_t code) {
    engine_cdda_stats.init_result = code;
    engine_cdda_stats.state = ENGINE_CDDA_FAILED;
    return 0;
}

int engine_cdda_start(uint32_t music_id, uint32_t start_offset_sectors) {
    const fzx_cdda_track_t *t = find(music_id);
    if (!t) return fail(16);
    /* No CD device connection: audio sectors must not fill the data buffers. */
    if (cd_block_cmd_cd_dev_connection_set(0xFFu)) return fail(17);
    uint8_t status; uint16_t words;
    if (cd_block_cmd_toc_get(&status, &words) || words < 204u) return fail(18);
    uint16_t last = cpu_frt_count_get(); uint32_t elapsed = 0;
    while (!(CD_HIRQ & HIRQ_DRDY)) {
        const uint16_t now = cpu_frt_count_get();
        elapsed += (uint16_t)(now - last); last = now;
        if (elapsed > TOC_TIMEOUT_TICKS) return fail(19);
    }
    uint32_t toc[102];
    for (unsigned i = 0; i < 102u; ++i) toc[i] = *CD_DATA;
    if (cd_block_cmd_data_transfer_end() < 0) return fail(20);
    if (t->track < 2u || t->track > 99u || (toc[t->track - 1u] >> 28) != 0u) return fail(21); /* control 0: 2-channel audio */
    const uint32_t fad = toc[t->track - 1u] & 0xFFFFFFu;
    engine_cdda_stats.track = t->track;
    engine_cdda_stats.track_fad = fad;
    engine_cdda_stats.end_fad = fad + t->sectors;
    if (t->loop_sector != FZX_CDDA_NO_LOOP) {
        loop_fad = fad + t->loop_sector;
        loop_sectors = t->sectors - t->loop_sector;
        engine_cdda_stats.loop_fad = loop_fad;
    }
    uint32_t start = fad, count = t->sectors;
    if (start_offset_sectors && start_offset_sectors < t->sectors) {
        start = fad + t->sectors - start_offset_sectors;
        count = start_offset_sectors;
    }
    command(FAD_FLAG | start, 0u, FAD_FLAG | count);
    send();
    engine_cdda_stats.state = ENGINE_CDDA_INTRO_SENT;
    engine_cdda_stats.init_result = 1;
    return 1;
}

void engine_cdda_service(void) {
    volatile engine_cdda_stats_t *s = &engine_cdda_stats;
    if (s->state == ENGINE_CDDA_OFF || s->state == ENGINE_CDDA_FAILED) return;
    send();
    if (want || !(CD_HIRQ & HIRQ_CMOK)) return;
    const uint32_t status = (uint32_t)(CD_CR1 >> 8) & 0x0Fu;
    s->last_status = status;
    s->last_fad = ((uint32_t)(CD_CR3 & 0xFFu) << 16) | CD_CR4;
    switch (s->state) {
    case ENGINE_CDDA_INTRO_SENT:
    case ENGINE_CDDA_LOOP_SENT:
        if (status == CD_STATUS_PLAY) {
            s->state = s->state == ENGINE_CDDA_INTRO_SENT ? ENGINE_CDDA_INTRO_PLAYING : ENGINE_CDDA_LOOPING;
            seen_play = 1;
        }
        break;
    case ENGINE_CDDA_INTRO_PLAYING:
        if ((status == CD_STATUS_PAUSE || status == CD_STATUS_STANDBY) && seen_play) {
            if (!loop_sectors) { s->state = ENGINE_CDDA_OFF; break; }   /* a one-shot piece ends */
            command(FAD_FLAG | loop_fad, PLAY_REPEAT_FOREVER, FAD_FLAG | loop_sectors);
            send();
            ++s->loop_backs;
            s->state = ENGINE_CDDA_LOOP_SENT;
        }
        break;
    default:
        break;
    }
}
