#define PUB_MARK(part) do{const uint16_t now_=cpu_frt_count_get();pub_add((part),(uint16_t)(now_-pub_last));pub_last=now_;}while(0)
#define PUB_END() do{pub_add(8,(uint16_t)(pub_last-pub_t0));}while(0)
