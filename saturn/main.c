/* The Saturn pad as the original code's N64 pad. A/C accelerate (A), B boost (B), Y brake
 * (C-down), L/R lean (Z/R); the D-pad is the stick at full deflection. Start restarts the race
 * (ref_race_restart), as the game's retry does. */
/* Test hook for scripted drives over the emulator's debugger (tools/emu/orig_drive.ps1):
 * when non-zero it replaces the pad, as N64 buttons << 16 | stick x << 8 | stick y. */
volatile uint32_t fzx_debug_n64;
/* Debugger autopilot (tools/emu/orig_drive.ps1 step AP): look-ahead in rings in the low byte,
 * a coast threshold in the next (throttle off while |stick| reaches it; 0 = never). Steers
 * towards the centreline ahead (fzx_steer_hint). A test driver for whole races, never a player
 * aid. */
volatile uint32_t fzx_debug_autopilot;

/* Every tick's input since the race (re)start, as N64 buttons << 16 | stick x << 8 | stick y:
 * a debugger reads it back as a host input script, so the host reference can replay a run. */
#define INPUT_LOG_TICKS 12288u /* 3.4 minutes: a whole race */
#if FZX_SOURCE_ROAD_TILES
extern volatile uint32_t fzx_input_log[INPUT_LOG_TICKS];
#else
volatile uint32_t fzx_input_log[INPUT_LOG_TICKS];
#endif
volatile uint32_t fzx_input_count;
/* Debugger fills the existing log while paused, then restarts. Each tick reads
 * its input before logged_tick writes the same slot. No added retail data. */
volatile uint32_t fzx_debug_replay_count;

#if FZX_SIMPIPE_PROFILE
static void simpipe_hash_tick(uint32_t word);
#endif
static void
logged_tick(uint16_t buttons, int8_t sx, int8_t sy)
{
    const uint32_t n = fzx_input_count;
    if (n < INPUT_LOG_TICKS) {
        fzx_input_log[n] = (uint32_t)buttons << 16 | (uint32_t)(uint8_t)sx << 8 | (uint8_t)sy;
        fzx_input_count = n + 1u;
    }
    ref_tick(buttons, sx, sy);
#if FZX_SIMPIPE_PROFILE
    /* Diagnostic only: the executed tick's own input word. */
    const uint32_t simpipe_word = (uint32_t)buttons << 16 | (uint32_t)(uint8_t)sx << 8 | (uint8_t)sy;
#endif
#if FZX_SOURCE_RESULTS
    if(!fzx_results_tick(digital.connected!=0)) {
        dbgio_printf("SOURCE RESULTS TICK FAILED %lu",(unsigned long)fzx_results_status);
        dbgio_flush();for(;;){}
    }
#endif
#if FZX_SOURCE_ROAD
    fzx_road_note_tick();
#endif
#if FZX_SOURCE_HUD
    RefHud source;
    ref_hud(&source);
    const fzx_hud_clock_input_t input = {
        source.lap, (uint32_t)source.race_time,
        {(uint32_t)source.lap_times[0], (uint32_t)source.lap_times[1],
         (uint32_t)source.lap_times[2]}, false
    };
    if (!fzx_hud_clock_step(&hud_clock, &input)) {
        fzx_source_hud_status = 4;
        for (;;) {}
    }
#endif
#if FZX_SIMPIPE_PROFILE
    simpipe_hash_tick(simpipe_word);
#endif
}

static void
orig_tick(void)
{
    if (fzx_debug_replay_count != 0) {
        const uint32_t n = fzx_input_count;
        /* Freeze simulation at the exact end while presentation keeps running. */
        if (n >= fzx_debug_replay_count || n >= INPUT_LOG_TICKS) return;
        const uint32_t word = fzx_input_log[n];
        logged_tick((uint16_t)(word >> 16), (int8_t)(word >> 8), (int8_t)word);
        return;
    }
    const uint16_t d = pad_down;
    uint16_t n64 = 0;
    int8_t sx = 0, sy = 0;
    if (fzx_debug_autopilot != 0) {
        const uint32_t ap = fzx_debug_autopilot;
        const int32_t sx = fzx_steer_hint(ap & 0xFFu);
        const int32_t coast = (int32_t)((ap >> 8) & 0xFFu);
        const bool off = coast != 0 && (sx >= coast || sx <= -coast);
        logged_tick(off ? 0 : 0x8000, (int8_t)sx, 0);
        return;
    }
    const uint32_t forced = fzx_debug_n64;
    if (forced != 0) {
        logged_tick((uint16_t)(forced >> 16), (int8_t)(forced >> 8), (int8_t)forced);
        return;
    }
    if (d & (PERIPHERAL_DIGITAL_A | PERIPHERAL_DIGITAL_C)) n64 |= 0x8000;
#if FZX_SOURCE_RESULTS
    if (d & PERIPHERAL_DIGITAL_START) n64 |= 0x1000;
#endif
    if (d & PERIPHERAL_DIGITAL_B) n64 |= 0x4000;
    if (d & PERIPHERAL_DIGITAL_L) n64 |= 0x2000;
    if (d & PERIPHERAL_DIGITAL_R) n64 |= 0x0010;
    if (d & PERIPHERAL_DIGITAL_Y) n64 |= 0x0004;
#if FZX_SOURCE_CAMERA
    if (d & PERIPHERAL_DIGITAL_X) n64 |= 0x0001; /* source C-right: view */
    if (d & PERIPHERAL_DIGITAL_Z) n64 |= 0x0008; /* source C-up: look back */
#endif
    if (d & PERIPHERAL_DIGITAL_LEFT) sx = -63;
    if (d & PERIPHERAL_DIGITAL_RIGHT) sx = 63;
    if (d & PERIPHERAL_DIGITAL_UP) sy = 63;
    if (d & PERIPHERAL_DIGITAL_DOWN) sy = -63;
    logged_tick(n64, sx, sy);
}


