#if FZX_ROAD_TILE_PROFILE
/* Pair the FRT and field clock inside one video field. This outer scope
 * independently detects an entire lost 16-bit wrap in the phase counters. */
volatile uint32_t fzx_road_profile_outer[2];
typedef struct {uint32_t fields;uint16_t ticks;} road_profile_clock_t;
static road_profile_clock_t road_profile_clock(void) {
    road_profile_clock_t result;uint32_t before;
    do {before=video_fields;result.ticks=cpu_frt_count_get();result.fields=video_fields;}
    while(before!=result.fields);
    return result;
}
#endif
static uint16_t pad_down;

/* Frame timing for hardware runs (docs/HARDWARE_TEST.md). The FRT runs free at the master
 * clock / 32; every figure is a difference of its 16-bit count, so it never needs a reset.
 * The vblank handler times the field itself, so percentages hold for NTSC, PAL and either
 * dot clock. Readable over a debugger as well as on screen. */
typedef struct {
    uint32_t magic;      /* 'FZXT' once counting */
    uint32_t loops;      /* main-loop iterations */
    uint32_t field;      /* FRT counts in the last field */
    uint32_t cpu;        /* FRT counts of CPU work in the last loop (sim + render + HUD) */
    uint32_t cpu_max;    /* worst since the last clear */
    uint32_t sim;        /* FRT counts of the original/proto ticks in the last loop */
    uint32_t sim_max;
    uint32_t misses;     /* loops that spanned more than one field since the last clear */
    uint32_t overload;   /* loops that ran the X+Z negative control */
    uint32_t publish;    /* FRT counts in the last loop: pose hand-over (orig only) */
    uint32_t render;     /*   the shared core's render and the VDP1 command build */
    uint32_t hud;        /*   the text HUD print and flush */
} fzx_timing_t;
volatile fzx_timing_t fzx_timing;
/* Debugger stand-in for holding X+Z (tools/emu/orig_drive.ps1 -Overload). */
volatile uint32_t fzx_debug_overload;
static volatile uint16_t vblank_frt;

static void
vblank_out(void *work)
{
    (void)work;
    const uint16_t now = cpu_frt_count_get();
    fzx_timing.field = (uint16_t)(now - vblank_frt);
    vblank_frt = now;
    ++video_fields;
#if FZX_FRAME_PROFILE
    fzx_fp_vblank(now,video_fields);
#endif
    smpc_peripheral_intback_issue();
}

void
user_init(void)
{
#if FZX_SOURCE_ROAD_STREAM
    /* Bound command storage by the actual scene capacity; retain the SDK's
     * separate Gouraud/CLUT reservations and return unused command VRAM to art. */
    const unsigned command_reserve=(COMMAND_CAPACITY+31u)&~31u;
    vdp1_vram_partitions_set(command_reserve,
        VDP1_VRAM_DEFAULT_TEXTURE_SIZE+(VDP1_VRAM_DEFAULT_CMDT_COUNT-command_reserve)*32u,
        VDP1_VRAM_DEFAULT_GOURAUD_COUNT,VDP1_VRAM_DEFAULT_CLUT_COUNT);
#endif
    smpc_peripheral_init();
    vdp2_tvmd_display_res_set(VDP2_TVMD_INTERLACE_NONE,
                            VDP2_TVMD_HORZ_NORMAL_A, VDP2_TVMD_VERT_224);
    vdp2_scrn_back_color_set(VDP2_VRAM_ADDR(3, 0x01FFFE),
                             RGB1555(1, 1, 2, 6));

    /* Yaul's default debug console uses NBG3 at priority 7. */
    vdp2_sprite_priority_set(0, 6);

    vdp1_env_t env;
    vdp1_env_default_init(&env);
    /* Transparent clear leaves the VDP2 back-screen color visible. */
    env.erase_color = RGB1555(0, 0, 0, 0);
    vdp1_env_set(&env);
    /* Variable interval: present only after the polygon list has finished. */
    vdp1_sync_interval_set(-1);

    vdp_sync_vblank_out_set(vblank_out, NULL);
    vdp2_tvmd_display_set();
}

static void
commands_init(void)
{
    const int16_vec2_t clip = INT16_VEC2_INITIALIZER(FZX_WIDTH - 1,
                                                   FZX_HEIGHT - 1);
    const int16_vec2_t origin = INT16_VEC2_INITIALIZER(0, 0);

    memset(commands_buf, 0, sizeof(commands_buf));
    for (uint32_t b = 0; b < COMMAND_BUFFER_COUNT; ++b) {
        vdp1_cmdt_t *const c = commands_buf[b];
        command_lists[b].cmdts = c;
        command_lists[b].count = 3;
        vdp1_cmdt_system_clip_coord_set(&c[COMMAND_SYSTEM_CLIP]);
        vdp1_cmdt_vtx_system_clip_coord_set(&c[COMMAND_SYSTEM_CLIP], clip);
        vdp1_cmdt_local_coord_set(&c[COMMAND_LOCAL_COORD]);
        vdp1_cmdt_vtx_local_coord_set(&c[COMMAND_LOCAL_COORD], origin);
        vdp1_cmdt_end_set(&c[COMMAND_FIRST_POLYGON]);
    }
}

static uint32_t
buttons_read(void)
{
    uint32_t buttons = 0;
    smpc_peripheral_process();
    smpc_peripheral_digital_port(1, &digital);
    if (!digital.connected) {
        return 0;
    }

    /* In Yaul, "pressed" is the current state; "held" is the down edge. */
    const uint16_t down = digital.pressed.raw;
    pad_down = down;
    if (down & PERIPHERAL_DIGITAL_LEFT)  buttons |= FZX_LEFT;
    if (down & PERIPHERAL_DIGITAL_RIGHT) buttons |= FZX_RIGHT;
    if (down & (PERIPHERAL_DIGITAL_A | PERIPHERAL_DIGITAL_C))
        buttons |= FZX_ACCEL;
    if (down & PERIPHERAL_DIGITAL_B) buttons |= FZX_BRAKE;
    if (digital.held.raw & PERIPHERAL_DIGITAL_START) buttons |= FZX_RESET;
    return buttons;
}

