#!/usr/bin/env python3
"""Attack and contact tables for the engine (lane claude/attacks), read from the decomp at build time.
Usage: attacks_tables.py DECOMP_DIR OUT_DIR
Reads src/game/racer.c (sDefaultMachines: body stat and weight per stock machine; gBodyHealthValues) and
src/overlays/ovl_i3/cpu.c (D_i3_8013E7A8: awareness bits and personality type per character;
D_i3_8013EBD0 / D_i3_8013EC30: attack chances by personality and difficulty). Writes
OUT_DIR/attacks_tables.h and attacks.receipt. The values are game data: the output stays local
(generated/ is git-ignored), never committed.

Per stock machine 0..29: the contact weight ((4 - body) * 312 + 780 + 312 * (weight - 780) / 1560)^2
(racer.c Racer_InitRacer; exact in integers since every weight is a multiple of 10), the maximum
energy (gBodyHealthValues[body], Q8), awareness and personality. Per personality and difficulty:
the side- and spin-attack chances in 1/32768."""
import hashlib, re, sys
from pathlib import Path

BODY = {'BODY_A': 0, 'BODY_B': 1, 'BODY_C': 2, 'BODY_D': 3, 'BODY_E': 4}


def floats(text, name):
    m = re.search(r'f32\s+' + re.escape(name) + r'\[\]\s*=\s*\{([^}]*)\}', text)
    if not m:
        raise SystemExit('missing table ' + name)
    return [float(x.strip().rstrip('f')) for x in m.group(1).split(',') if x.strip()]


def main():
    decomp, out = Path(sys.argv[1]), Path(sys.argv[2])
    racer = (decomp / 'src/game/racer.c').read_text()
    cpu = (decomp / 'src/overlays/ovl_i3/cpu.c').read_text()
    m = re.search(r'Machine\s+sDefaultMachines\[\]\s*=\s*\{(.*?)\n\};', racer, re.S)
    if not m:
        raise SystemExit('missing sDefaultMachines')
    machines = re.findall(r'\{\s*BODY_[A-E][^}]*\},\s*(\d+)\s*\}', m.group(1))
    bodies = re.findall(r'\{\s*(BODY_[A-E])\s*,', m.group(1))
    if len(machines) < 30 or len(bodies) < 30:
        raise SystemExit('expected 30 stock machines')
    health = floats(racer, 'gBodyHealthValues')
    m = re.search(r'D_i3_8013E7A8\[\]\s*=\s*\{(.*?)\n\};', cpu, re.S)
    if not m:
        raise SystemExit('missing D_i3_8013E7A8')
    pers = re.findall(r'\{\s*(\d+)\s*,\s*(\d+)\s*,\s*\{', m.group(1))
    if len(pers) < 30:
        raise SystemExit('expected 30 CPU characters')
    side = floats(cpu, 'D_i3_8013EBD0')
    spin = floats(cpu, 'D_i3_8013EC30')
    rows = []
    for i in range(30):
        body = BODY[bodies[i]]
        weight = int(machines[i])
        assert (weight - 780) % 5 == 0
        s = (4 - body) * 312 + 780 + (weight - 780) // 5
        rows.append((s * s, int(round(health[body] * 256)), body, weight, int(pers[i][0]), int(pers[i][1])))
    out.mkdir(parents=True, exist_ok=True)
    h = out / 'attacks_tables.h'
    with open(h, 'w', newline='\n') as o:
        o.write('/* Generated by tools/attacks_tables.py from the decomp (racer.c, cpu.c): game data, local only;'
                ' regenerate, never edit, never commit. */\n')
        o.write('#ifndef FZX_ATTACKS_TABLES_H\n#define FZX_ATTACKS_TABLES_H\n#include <stdint.h>\n')
        o.write('/* per stock machine: contact weight, max energy Q8, body stat, weight, awareness bits, personality */\n')
        o.write('static const uint32_t fzx_atk_machine[30][6] = {\n')
        for r in rows:
            o.write('    {%du, %du, %du, %du, %du, %du},\n' % r)
        o.write('};\n')
        npers = len(side) // 4
        o.write('/* side-attack chance and side+spin chance in 1/32768, by personality * 4 + difficulty */\n')
        o.write('#define FZX_ATK_PERSONALITIES %du\n' % npers)
        o.write('static const uint16_t fzx_atk_chance[%d][2] = {\n' % len(side))
        for k in range(len(side)):
            a = int(round(side[k] * 32768))
            b = int(round((side[k] + spin[k]) * 32768))
            o.write('    {%du, %du},\n' % (a, b))
        o.write('};\n#endif\n')
    rec = ['# fzx generation receipt v1; regenerate, never edit',
           'generator %s attacks_tables.py' % hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
           'output %s attacks_tables.h' % hashlib.sha256(h.read_bytes()).hexdigest()]
    with open(out / 'attacks.receipt', 'w', newline='\n') as o:
        o.write('\n'.join(rec) + '\n')
    print('attacks tables: 30 machines, %d personality rows' % len(side))


if __name__ == '__main__':
    main()
