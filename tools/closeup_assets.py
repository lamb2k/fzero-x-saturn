#!/usr/bin/env python3
"""Engine E1 close-up A/B, arm A: the 3D player's CD pack and body colour.

MACHAB.PAK is the prepared vehicle (tools/machine_rebake.py: MACHRLD.PAK metadata,
then MACHRTX.PAK texels) as one CD file. The 3D model's body-tinted palettes take
the racer's body colour, which the legacy draw read from the running game; the
engine image has no game to read, so the identity header carries the colour of
the skin the player's sprite sets are baked with (the source machine table's
family 0, skin 1 by default). Outputs go to the git-ignored generated/closeup; the
receipt records hashes, never the data.

    tools/closeup_assets.py [--skin 1] [--rebake generated/machine_rebake] [--output generated/closeup]
"""
import argparse
import hashlib
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import racer_sprites  # noqa: E402

GENERATORS = ('tools/closeup_assets.py', 'tools/racer_sprites.py')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def fnv32(data):
    """FNV-1a 32, the engine CD loader's check."""
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--skin', type=int, default=racer_sprites.DEFAULT_VIEWS['skin'])
    ap.add_argument('--family', type=int, default=0, help='stock family whose skin colours the body')
    ap.add_argument('--output', type=Path, default=ROOT / 'generated/closeup')
    ap.add_argument('--rebake', type=Path, default=ROOT / 'generated/machine_rebake', help='tools/machine_rebake.py output')
    args = ap.parse_args()
    out = args.output.resolve()
    if not out.is_relative_to((ROOT / 'generated').resolve()):
        ap.error('output must stay in generated/')
    families = racer_sprites.source_families()
    if not 0 <= args.family < racer_sprites.STOCK_FAMILIES:
        ap.error('unknown stock family')
    skins = families[args.family]['skins']
    if not 0 <= args.skin < len(skins):
        ap.error('unknown skin')
    r, g, b = skins[args.skin][:3]
    # One CD file for the prepared vehicle (the engine's CD loader reads at most 16
    # root entries): MACHRLD.PAK (metadata) then MACHRTX.PAK (texels), as baked.
    rebake = args.rebake.resolve()
    meta, texels = (rebake / 'MACHRLD.PAK').read_bytes(), (rebake / 'MACHRTX.PAK').read_bytes()
    pak = meta + texels
    if len(meta) & 3 or len(texels) & 3:
        ap.error('vehicle packs must be whole words')
    out.mkdir(parents=True, exist_ok=True)
    header = ('/* Generated by tools/closeup_assets.py; regenerate, never edit. */\n'
              '#ifndef FZX_CLOSEUP_IDENTITY_H\n#define FZX_CLOSEUP_IDENTITY_H\n'
              '#define FZX_CLOSEUP_BODY_R %uu\n#define FZX_CLOSEUP_BODY_G %uu\n#define FZX_CLOSEUP_BODY_B %uu\n'
              '#define FZX_CLOSEUP_PACK_BYTES %uu\n#define FZX_CLOSEUP_PACK_HASH 0x%08Xu\n'
              '#define FZX_CLOSEUP_META_BYTES %uu\n#define FZX_CLOSEUP_TEXEL_BYTES %uu\n'
              '#endif\n' % (r, g, b, len(pak), fnv32(pak), len(meta), len(texels))).encode()
    (out / 'MACHAB.PAK').write_bytes(pak)
    (out / 'closeup_identity.h').write_bytes(header)
    lines = ['# fzx generation receipt v1; regenerate, never edit']
    for rel in GENERATORS:
        lines.append('generator %s %s' % (sha((ROOT / rel).read_bytes()), os.path.relpath(ROOT / rel, ROOT / 'tools').replace('\\', '/')))
    lines.append('input %s machine-table' % sha(racer_sprites.machine_menu_models.RACER.read_bytes()))
    lines.append('input %s skin-%d' % (sha(str(args.skin).encode()), args.skin))
    if args.family:
        lines.append('input %s family-%d' % (sha(str(args.family).encode()), args.family))
    lines.append('input %s machine-rebake-metadata' % sha(meta))
    lines.append('input %s machine-rebake-texels' % sha(texels))
    lines.append('output %s MACHAB.PAK' % sha(pak))
    lines.append('output %s closeup_identity.h' % sha(header))
    (out / 'closeup.receipt').write_bytes(('\n'.join(lines) + '\n').encode())
    print('closeup assets written (skin %d)' % args.skin)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
