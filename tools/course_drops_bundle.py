#!/usr/bin/env python3
"""Drop node ranges for the one-disc image (ENG_RIVAL_BEHAVE with ENG_COURSE_SELECT; line-field-5 falls).

Reads each bundled course's rivals/drops.txt (tools/rivals_drops.py; a course without one has no drop nodes) and
writes, next to tools/course_bundle.py's outputs:
    generated/courses/select/course_drops.h    fzx_course_drops[course row][8][2], fzx_course_drop_count[course row]
    generated/courses/select/course_drops.c
    generated/courses/select/course_drops.receipt
The course rows follow the existing course_ids.c (checked). course_bundle.py and its outputs are untouched.
Everything here is derived from the owner's ROM: generated/ only, never committed.

    tools/course_drops_bundle.py mute-city-1 silence-1 sand-ocean-1 devils-forest-1 big-blue-1 port-town-1
"""
import hashlib, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import course_catalog  # noqa: E402
from course_bundle import OUT, ROOT  # noqa: E402

MAX = 8


def main():
    slugs = sys.argv[1:] or list(course_catalog.COURSES)
    ids = [int(v) for v in re.findall(r'\.id = (\d+)u', (OUT / 'course_ids.c').read_text())]
    if ids != [course_catalog.course(s)['index'] for s in slugs]:
        raise SystemExit('give the courses in course_ids.c order (course indexes %s)' % ids)
    rows, inputs = [], []
    for s in slugs:
        p = course_catalog.gen_root(s) / 'rivals/drops.txt'
        r = []
        if p.exists():
            inputs.append(p)
            r = [tuple(int(v) for v in ln.split()) for ln in p.read_text().splitlines() if ln.strip() and not ln.startswith('#')]
        if len(r) > MAX:
            raise SystemExit('%s: more than %d ranges' % (p, MAX))
        rows.append(r)
    h = ['/* Generated by tools/course_drops_bundle.py; derived from the owner\'s ROM: never commit. */',
         '#ifndef FZX_COURSE_DROPS_H', '#define FZX_COURSE_DROPS_H', '#include <stdint.h>', '#include "course_ids.h"',
         '#define FZX_COURSE_DROP_MAX %du' % MAX,
         'extern const uint16_t fzx_course_drops[FZX_COURSE_IDS_COUNT][FZX_COURSE_DROP_MAX][2];',
         'extern const uint8_t fzx_course_drop_count[FZX_COURSE_IDS_COUNT];', '#endif', '']
    c = ['/* Generated by tools/course_drops_bundle.py; derived from the owner\'s ROM: never commit. */',
         '#include "course_drops.h"',
         'const uint16_t fzx_course_drops[FZX_COURSE_IDS_COUNT][FZX_COURSE_DROP_MAX][2] = {']
    for r in rows:
        c.append('  { %s },' % (', '.join('{ %d, %d }' % x for x in r) or '{ 0, 0 }'))
    c += ['};', 'const uint8_t fzx_course_drop_count[FZX_COURSE_IDS_COUNT] = { %s };' % ', '.join(str(len(r)) for r in rows), '']
    (OUT / 'course_drops.h').write_bytes('\n'.join(h).encode())
    (OUT / 'course_drops.c').write_bytes('\n'.join(c).encode())
    sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    rec = ['# fzx generation receipt v1; regenerate, never edit',
           'generator %s course_drops_bundle.py' % sha(Path(__file__)),
           'generator %s course_bundle.py' % sha(ROOT / 'tools/course_bundle.py'),
           'generator %s course_catalog.py' % sha(ROOT / 'tools/course_catalog.py')]
    rec += ['input %s %s' % (sha(p), p.relative_to(ROOT / 'generated')) for p in inputs]
    rec += ['output %s %s' % (sha(OUT / n), n) for n in ('course_drops.h', 'course_drops.c')]
    (OUT / 'course_drops.receipt').write_bytes(('\n'.join(rec) + '\n').encode())
    print('course drops bundle: %s' % ', '.join('%s %d' % (s, len(r)) for s, r in zip(slugs, rows)))


if __name__ == '__main__':
    main()
