#!/usr/bin/env python3
"""Decal packs for the one-disc image (ENG_GADGETS with ENG_COURSE_SELECT).

Reads each bundled course's road_gadget identity (tools/gadget_bake.py) and writes, next to tools/course_bundle.py's
outputs:
    generated/courses/select/course_gadgets.h   fzx_course_gadgets[course row]: disc name, sizes, hashes and table rows
    generated/courses/select/course_gadgets.c
    generated/courses/select/gadget_files.txt   "<generated path> <disc name>" for the disc staging (RGAD<n>.PAK)
    generated/courses/select/course_gadgets.receipt
The course rows follow the existing course_ids.c (checked) and carry the course id; the image looks its row up by id (it
copies the selected course_ids row to high work RAM, so a pointer difference is no index). course_bundle.py and its
outputs are untouched.
Everything here is derived from the owner's ROM: generated/ only, never committed.

    tools/course_gadget_bundle.py mute-city-1 silence-1 sand-ocean-1 devils-forest-1 big-blue-1 port-town-1
"""
import hashlib, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import course_catalog  # noqa: E402
from course_bundle import OUT, ROOT, defines, num  # noqa: E402

TABLES = ('GFIRST', 'GPOS', 'GQUADS', 'GIMAGES', 'GTEX')


def main():
    slugs = sys.argv[1:] or list(course_catalog.COURSES)
    ids = [int(v) for v in re.findall(r'\.id = (\d+)u', (OUT / 'course_ids.c').read_text())]
    if ids != [course_catalog.course(s)['index'] for s in slugs]:
        raise SystemExit('give the courses in course_ids.c order (course indexes %s)' % ids)
    rows, files = [], []
    for s in slugs:
        g = course_catalog.gen_root(s) / 'road_gadget'
        d = defines(g / 'road_gadget_identity.h')
        name = 'RGAD%d.PAK' % course_catalog.course(s)['index']
        rows.append((name, d))
        files.append((g / 'ROADGAD.PAK', name))
    h = ['/* Generated by tools/course_gadget_bundle.py; derived from the owner\'s ROM: never commit. */',
         '#ifndef FZX_COURSE_GADGETS_H', '#define FZX_COURSE_GADGETS_H', '#include <stdint.h>', '#include "course_ids.h"',
         'typedef struct {', '    uint8_t id;', '    char file[12];', '    uint32_t bytes, hash, chunks, quads, images, tex_bytes;',
         '    fzx_course_table_t table[5];   /* GFIRST, GPOS, GQUADS, GIMAGES, GTEX */', '} fzx_course_gadgets_t;',
         'extern const fzx_course_gadgets_t fzx_course_gadgets[FZX_COURSE_IDS_COUNT];', '#endif', '']
    c = ['/* Generated by tools/course_gadget_bundle.py; derived from the owner\'s ROM: never commit. */',
         '#include "course_gadgets.h"', 'const fzx_course_gadgets_t fzx_course_gadgets[FZX_COURSE_IDS_COUNT] = {']
    for name, d in rows:
        t = ', '.join('{ %du, %du, %du }' % (num(d['FZX_ROAD_GAD_%s_AT' % k]), num(d['FZX_ROAD_GAD_%s_BYTES' % k]),
                                             num(d['FZX_ROAD_GAD_%s_HASH' % k])) for k in TABLES)
        c.append('  { %du, "%s", %du, %du, %du, %du, %du, %du, { %s } },' % (
            int(name[4:-4]), name, num(d['FZX_ROAD_GAD_BYTES']), num(d['FZX_ROAD_GAD_FILE_HASH']), num(d['FZX_ROAD_GAD_CHUNKS']),
            num(d['FZX_ROAD_GAD_QUADS']), num(d['FZX_ROAD_GAD_IMAGES']), num(d['FZX_ROAD_GAD_TEX_BYTES']), t))
    c += ['};', '']
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'course_gadgets.h').write_bytes('\n'.join(h).encode())
    (OUT / 'course_gadgets.c').write_bytes('\n'.join(c).encode())
    (OUT / 'gadget_files.txt').write_bytes(''.join('%s %s\n' % (p.relative_to(ROOT / 'generated'), n) for p, n in files).encode())
    sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    rec = ['# fzx generation receipt v1; regenerate, never edit',
           'generator %s course_gadget_bundle.py' % sha(Path(__file__)),
           'generator %s course_bundle.py' % sha(ROOT / 'tools/course_bundle.py'),
           'generator %s course_catalog.py' % sha(ROOT / 'tools/course_catalog.py')]
    rec += ['input %s %s' % (sha(p), p.relative_to(ROOT / 'generated')) for p, _ in files]
    rec += ['output %s %s' % (sha(OUT / n), n) for n in ('course_gadgets.h', 'course_gadgets.c', 'gadget_files.txt')]
    (OUT / 'course_gadgets.receipt').write_bytes(('\n'.join(rec) + '\n').encode())
    print('course gadget bundle: %s' % ', '.join('%s %d' % (s, num(d['FZX_ROAD_GAD_QUADS'])) for s, (_, d) in zip(slugs, rows)))


if __name__ == '__main__':
    main()
