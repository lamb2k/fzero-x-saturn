#!/usr/bin/env python3
"""Death Race field rows (course 54) for the one-disc image, from the HOST reference (fzx-gp-ref --mode death, seed 1) alone.

The original has no field table for the mode: Racer_Init runs the same Cpu_InitRacer as the Grand Prix (racer.c 2173-2236, cpu.c 474-540),
the CPU line is the default (speed 69, lateral 0), there are no pace tables, and every rival's energy is halved. The rivals' pace before they
fly off the air run is therefore the reference's own, per rival and per seed (tools/ ... explore: it varies by seed and is not a function of
machine or id), so a shipped field bakes one table: the seed-1 table, applied by id (C-169 item 2). Per rival the table is the mean distance
covered a tick over the 30 ticks before its first air tick (progress from air-31 to air-1, divided by 30), read from the reference's per-tick
diagnostic (fzx-gp-ref --diag: 88-byte rows, 10 i32 then 12 f32; flags at int 2, distance at float 0, air = flag bit 26), turned into the
target lap time in ms the field config takes: round(course_length / speed * 1000 / 60). The method was frozen (HOST qualification on fresh
seeds 31..38, tools/modes_dr_check.py) before any qualification run.

    tools/death_field_header.py REF.json DIAG.bin OUT_CLASS.h [OUT_TABLE.json [OUT_FIELD.h]]

OUT_FIELD.h is rivals_field.h's shape (fzx_rivals_field[30][8]), the same rows once: the course row's own field (tools/course_bundle.py).

OUT_CLASS.h has fzx_rivals_field_class[4][30][8] (the course class bundle's input) with the same rows in all four classes: Death Race is
Master only, and the class the engine reads is the session's. Columns as rivals_field.h: grid, target lap ms, chase (255 none), max energy
Q8, aggression, character, finish ms (0), first-lap cap (0). The rivals' energy is the FULL value (the reference's halved energy doubled):
the engine halves it with the mode (engine_modes.c, 128/256). The player's row keeps its energy.
Derived from the owner's ROM: generated/ only, never committed."""
import collections, json, struct, sys

AIR = 1 << 26


def pace_table(diag, rec=88):
    d = open(diag, 'rb').read()
    rows = collections.defaultdict(dict)
    for k in range(len(d) // rec):
        ri = struct.unpack_from('<10i', d, k * rec)
        rf = struct.unpack_from('<12f', d, k * rec + 40)
        rows[ri[1]][ri[0]] = (ri[2], rf[0])
    sp = {}
    for i, r in rows.items():
        if i == 0:
            continue
        air = min(t for t, (fl, dist) in r.items() if fl & AIR)
        sp[i] = (r[air - 1][1] - r[air - 31][1]) / 30.0
    if sorted(sp) != list(range(1, 30)):
        raise SystemExit('the pace table needs all 29 rivals, got %d' % len(sp))
    return sp


def rows_of(ref, sp):
    if ref.get('tier') != 'HOST' or int(ref.get('seed', -1)) != 1 or int(ref.get('difficulty', -1)) != 1:
        raise SystemExit('the reference must be the HOST report at seed 1, difficulty 1')
    racers = sorted(ref['racers'], key=lambda x: x['id'])
    if [x['id'] for x in racers] != list(range(30)):
        raise SystemExit('reference ids must run 0..29')
    out = []
    for x in racers:
        chase = x['chase']
        aggression = 38 if chase not in (0, 255) else 0
        if x['id'] == 0:
            out.append((x['grid'], 0, chase, int(round(x['max_energy'] * 256)), aggression, x['character'], 0, 0))
        else:
            lap_ms = round(ref['course_length'] / sp[x['id']] * 1000 / 60)
            out.append((x['grid'], lap_ms, chase, int(round(x['max_energy'] * 2 * 256)), aggression, x['character'], 0, 0))
    if sorted(r[0] for r in out) != list(range(1, 31)) or len({r[5] for r in out[1:]}) != 29:
        raise SystemExit('grid places 1..30 and 29 distinct machines expected')
    return out


def main():
    a = sys.argv[1:]
    if len(a) not in (3, 4, 5):
        sys.exit(__doc__)
    ref = json.load(open(a[0]))
    sp = pace_table(a[1])
    rows = rows_of(ref, sp)
    with open(a[2], 'w', newline='\n') as o:
        o.write("/* Generated by tools/death_field_header.py from the HOST Death Race report and its per-tick diagnostic; derived from the owner's ROM: "
                "regenerate, never edit, never commit. */\n#ifndef FZX_RIVALS_FIELD_CLASS_H\n#define FZX_RIVALS_FIELD_CLASS_H\n#define FZX_RIVALS_FIELD_CLASS_SEED 1u\n")
        o.write('/* [class][vehicle]: the same rows in every class (Death Race is Master only); rivals at full energy, the mode halves it */\n')
        o.write('static const int32_t fzx_rivals_field_class[4][30][8] = {\n')
        for _ in range(4):
            o.write('  {\n')
            for r in rows:
                o.write('    {%s},\n' % ', '.join(str(v) for v in r))
            o.write('  },\n')
        o.write('};\n#endif\n')
    if len(a) == 5:
        with open(a[4], 'w', newline='\n') as o:
            o.write("/* Generated by tools/death_field_header.py (HOST Death Race report); derived from the owner's ROM: "
                    "regenerate, never edit, never commit. */\n#ifndef FZX_RIVALS_FIELD_H\n#define FZX_RIVALS_FIELD_H\n"
                    "#define FZX_RIVALS_FIELD_COUNT 30u\n#define FZX_RIVALS_FIELD_SEED 1u\n"
                    "/* grid, target_lap_ms, chase (255 none), max_energy Q8, aggression, character, finish_ms, first-lap chase cap Q8 (0 none) */\n"
                    "static const int32_t fzx_rivals_field[30][8] = {\n")
            for r in rows:
                o.write('    {%s},\n' % ', '.join(str(v) for v in r))
            o.write('};\n#endif\n')
    if len(a) >= 4:
        json.dump({str(i): sp[i] for i in sorted(sp)}, open(a[3], 'w'), indent=0)
    print('death field header: 30 vehicles, pre-take-off speed min %.2f max %.2f' % (min(sp.values()), max(sp.values())))


if __name__ == '__main__':
    main()
