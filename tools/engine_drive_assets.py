#!/usr/bin/env python3
"""Engine E1 drive assets: the physics pack for the engine image's CD.

Bakes PHYS.PAK from a physics source (fzx-ref --bake; tools/physics_pack.py) and writes
the identity header the engine checks it against (bytes and the CD loader's FNV-1a 32).
The pack is derived from the owner's ROM and course data: the output goes to the
git-ignored generated/ folder only, and the receipt records hashes, never the data.

    tools/engine_drive_assets.py --source BAKE_SOURCE [--output generated/physics] [--laps 3]
"""
import argparse
import hashlib
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import physics_pack  # noqa: E402

GENERATORS = ('tools/engine_drive_assets.py', 'tools/physics_pack.py')


def fnv32(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--source', type=Path, required=True, help='physics source written by fzx-ref --bake')
    ap.add_argument('--output', type=Path, default=ROOT / 'generated/physics')
    ap.add_argument('--laps', type=int, default=3)
    args = ap.parse_args()
    out = args.output
    out.mkdir(parents=True, exist_ok=True)
    src = physics_pack.parse(args.source)
    pack = physics_pack.build(src, args.laps)
    if len(pack) & 3:
        pack += b'\0' * (4 - (len(pack) & 3))
    (out / 'PHYS.PAK').write_bytes(pack)
    (out / 'physics_identity.h').write_text(
        '/* Generated by tools/engine_drive_assets.py; regenerate, never edit. */\n'
        '#ifndef FZX_PHYSICS_IDENTITY_H\n#define FZX_PHYSICS_IDENTITY_H\n'
        '#define FZX_PHYSICS_PACK_BYTES %uu\n#define FZX_PHYSICS_PACK_HASH 0x%08Xu\n'
        '#define FZX_PHYSICS_PACK_LAPS %uu\n#endif\n' % (len(pack), fnv32(pack), args.laps))
    lines = ['# fzx generation receipt v1; regenerate, never edit']
    tools_dir = ROOT / 'tools'
    for rel in GENERATORS:
        lines.append('generator %s %s' % (sha(ROOT / rel), os.path.relpath(ROOT / rel, tools_dir)))
    lines.append('input %s physics-source' % sha(args.source))
    for name in ('PHYS.PAK', 'physics_identity.h'):
        lines.append('output %s %s' % (sha(out / name), name))
    (out / 'physics.receipt').write_text('\n'.join(lines) + '\n')
    print('engine physics pack: %d bytes, fnv 0x%08x, %d laps' % (len(pack), fnv32(pack), args.laps))


if __name__ == '__main__':
    main()
