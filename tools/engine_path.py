#!/usr/bin/env python3
"""Bake the engine's camera path and course constants (ENGPATH.PAK, E0).

Inputs are two private HOST dumps of the reference race on the owner's course
(ref/sim_build.sh with FZX_ENGINE_DUMP=1, then fzx-sim --camera-trace and
--engine-course). Nothing here or in the outputs is committed: the outputs
land in generated/engine_path, which git ignores. Run under Linux/WSL.
"""
import argparse, hashlib, json, os, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATORS = ('tools/engine_path.py', 'tools/engine_bake.c', 'saturn/engine/engine_scene.c',
              'saturn/engine/engine_scene.h', 'saturn/engine/engine_path.c', 'saturn/engine/engine_path.h',
              'src/fzx_view.c', 'include/fzx_view.h', 'ref/engine_dump.c', 'ref/backdrop_state.h',
              'ref/skyline_state.h', 'ref/road_plan.h')


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--raw', type=Path, default=ROOT/'generated/engine_path/raw',
                    help='directory holding camera.txt and course.txt')
    ap.add_argument('--output', type=Path, default=ROOT/'generated/engine_path')
    ap.add_argument('--sh2zam', type=Path, default=ROOT/'third_party/SH2ZAM',
                    help='SH2ZAM checkout for the host build of src/fzx_view.c')
    ap.add_argument('--fog', default='252,192,253', help='course fog colour R,G,B (generated/road_pack/road_identity.h)')
    args = ap.parse_args()
    out = args.output.resolve()
    camera, course = args.raw/'camera.txt', args.raw/'course.txt'
    for p in (camera, course, *(ROOT/g for g in GENERATORS)):
        if not Path(p).is_file():
            raise SystemExit('engine path: missing input %s' % p)
    out.mkdir(parents=True, exist_ok=True)
    tool = out/'engine_bake'
    subprocess.run(['gcc', '-O2', '-Wall', '-Wextra', '-Werror', '-I', ROOT/'include', '-I', ROOT/'ref',
                    '-I', ROOT/'saturn/engine', '-I', args.sh2zam/'saturn/include', ROOT/'src/fzx_view.c',
                    ROOT/'saturn/engine/engine_scene.c', ROOT/'saturn/engine/engine_path.c', args.sh2zam/'saturn/src/sh2zam_segmesh.c',
                    ROOT/'tools/engine_bake.c', '-lm', '-o', tool], check=True)
    r = subprocess.run([tool, 'bake', camera, course, out/'ENGPATH.PAK'], check=True, capture_output=True,
                       text=True, env={**os.environ, 'ENGINE_FOG': args.fog})
    fields = dict(zip(r.stdout.split()[0::2], r.stdout.split()[1::2]))
    pack = (out/'ENGPATH.PAK').read_bytes()
    file_hash = 2166136261
    for b in pack:
        file_hash = ((file_hash ^ b) * 16777619) & 0xffffffff
    if len(pack) != int(fields['bytes']):
        raise SystemExit('engine path: pack size mismatch')
    header = ['/* Generated by tools/engine_path.py; regenerate, never edit. */',
              '#ifndef FZX_ENGINE_PATH_IDENTITY_H', '#define FZX_ENGINE_PATH_IDENTITY_H',
              '#define FZX_ENGINE_PATH_BYTES %du' % len(pack),
              '#define FZX_ENGINE_PATH_HASH 0x%su' % fields['hash'],
              '#define FZX_ENGINE_PATH_FILE_HASH 0x%08xu' % file_hash,
              '#define FZX_ENGINE_PATH_TICKS %su' % fields['ticks'],
              '#define FZX_ENGINE_PATH_CHUNKS %su' % fields['chunks'], '#endif', '']
    (out/'engine_path_identity.h').write_text('\n'.join(header))
    report = dict(bytes=len(pack), fnv1a=fields['hash'], ticks=int(fields['ticks']), chunks=int(fields['chunks']),
                  anchor_shift=int(fields['shift']), sectors=(len(pack) + 2047)//2048,
                  inputs=dict(camera=sha(camera), course=sha(course)), fog=args.fog)
    (out/'engine_path.json').write_text(json.dumps(report, indent=1, sort_keys=True) + '\n')
    tool.unlink()
    lines = ['# fzx generation receipt v1; regenerate, never edit']
    tools_dir = ROOT/'tools'
    for rel in GENERATORS:
        lines.append('generator %s %s' % (sha(ROOT/rel), os.path.relpath(ROOT/rel, tools_dir)))
    for name in ('ENGPATH.PAK', 'engine_path_identity.h', 'engine_path.json'):
        lines.append('output %s %s' % (sha(out/name), name))
    (out/'engine_path.receipt').write_text('\n'.join(lines) + '\n')
    print('engine path: %d bytes, %s ticks, %s chunks, fnv 0x%s' % (len(pack), fields['ticks'], fields['chunks'], fields['hash']))


if __name__ == '__main__':
    main()
