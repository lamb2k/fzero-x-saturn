#!/usr/bin/env python3
"""The parts of the engine path pack the drive image reads (scenes lane, ENG_SCENES).

The E1 drive takes its camera from the physics; of ENGPATH.PAK (generated/engine_path) it
needs only the header and the chunk anchors (the track pick) and one camera record (the
race camera's lens). This writes generated/engine_path_ranges/engine_path_ranges.h with
those two byte ranges and the FNV-1a of each, which the image checks as it reads them, so
it reads about 2 KB of the 566 KB pack. The receipt pins ENGPATH.PAK's own receipt.

Everything read or written here derives from the owner's ROM: generated/ only.

    tools/engine_path_ranges.py
"""
import hashlib, os, struct, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
G = ROOT / 'generated'
LENS_TICK = 3000  # engine_main.c: the lens of the race camera at speed, path tick 3000 (or the last)


def fnv(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h


def main():
    src = G / 'engine_path'
    subprocess.run(['sh', str(ROOT / 'tools/check_receipt.sh'), str(src / 'engine_path.receipt')], check=True, stdout=subprocess.DEVNULL)
    b = (src / 'ENGPATH.PAK').read_bytes()
    W = lambda n: struct.unpack_from('>I', b, 4 * n)[0]
    ticks, record, records = W(4), W(5), W(30)
    if records & 3 or record & 3 or records + ticks * record != len(b):
        print('engine_path_ranges: unexpected layout', file=sys.stderr); return 1
    lens = (ticks if ticks < LENS_TICK else LENS_TICK) - 1
    lens_at = records + lens * record
    out = G / 'engine_path_ranges'
    out.mkdir(parents=True, exist_ok=True)
    h = '\n'.join([
        '/* Generated by tools/engine_path_ranges.py; derived from the owner\'s ROM: never commit. */',
        '#ifndef FZX_ENGINE_PATH_RANGES_H', '#define FZX_ENGINE_PATH_RANGES_H',
        '#define FZX_EPATH_HEAD_BYTES %du' % records, '#define FZX_EPATH_HEAD_HASH 0x%08Xu' % fnv(b[:records]),
        '#define FZX_EPATH_LENS_TICK %du' % (lens + 1), '#define FZX_EPATH_LENS_AT %du' % lens_at,
        '#define FZX_EPATH_LENS_BYTES %du' % record, '#define FZX_EPATH_LENS_HASH 0x%08Xu' % fnv(b[lens_at:lens_at + record]),
        '#endif', '']).encode()
    (out / 'engine_path_ranges.h').write_bytes(h)
    sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
    rec = ['# fzx generation receipt v1; regenerate, never edit',
           'generator %s engine_path_ranges.py' % sha(__file__),
           'generator %s ../generated/engine_path/engine_path.receipt' % sha(src / 'engine_path.receipt'),
           'input %s ENGPATH.PAK' % hashlib.sha256(b).hexdigest(),
           'output %s engine_path_ranges.h' % hashlib.sha256(h).hexdigest()]
    (out / 'engine_path_ranges.receipt').write_bytes(('\n'.join(rec) + '\n').encode())
    print('engine path ranges: head %d bytes, lens record at %d' % (records, lens_at))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
