#!/usr/bin/env python3
"""The scenes image's per-family 3D player packs from the engine's per-family close-up assets.

The engine builds each family's prepared vehicle with tools/machine_rebake.py and
tools/closeup_assets.py into generated/machine_rebake[_fNN] and generated/closeup[_fNN]
(MACHAB.PAK, closeup_identity.h). This collects the families the select screen offers into
generated/mach3d_scn: MACH3Dnn.PAK (each one family's MACHAB.PAK, byte for byte) and
mach3d_identity.h in the table form engine_closeup.c reads (indexed by family), with a
receipt that pins every source receipt, so a re-bake of any of them makes this stale.

Everything read or written comes from the owner's ROM: generated/ only, never committed.

    tools/mach3d_from_closeup.py [--families 0,1,3]
"""
import argparse, hashlib, os, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
G = ROOT / 'generated'


def defines(path):
    out = {}
    for line in path.read_text().splitlines():
        m = re.match(r'#define (\w+) (\d+)u', line)
        if m:
            out[m.group(1)] = int(m.group(2))
        m = re.match(r'#define (\w+) 0x([0-9A-Fa-f]+)u', line)
        if m:
            out[m.group(1)] = int(m.group(2), 16)
    return out


def fnv(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--families', default='0,1,3')
    ap.add_argument('--output', type=Path, default=G / 'mach3d_scn')
    a = ap.parse_args()
    fams = [int(f) for f in a.families.split(',')]
    sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
    rows, rec, outputs = {}, [], {}
    for f in fams:
        sfx = '' if f == 0 else '_f%02d' % f
        cu, mr = G / ('closeup' + sfx), G / ('machine_rebake' + sfx)
        # The close-up receipt pins the prepared vehicle's bytes (its inputs are the rebake's
        # metadata and texels); the rebake identity's sizes and hashes are checked against the pack.
        r = cu / 'closeup.receipt'
        subprocess.run(['sh', str(ROOT / 'tools/check_receipt.sh'), str(r)], check=True, stdout=subprocess.DEVNULL)
        for p in (r, mr / 'machine_rebake_identity.h'):
            rec.append('generator %s %s' % (sha(p), os.path.relpath(p, ROOT / 'tools').replace('\\', '/')))
        c, m = defines(cu / 'closeup_identity.h'), defines(mr / 'machine_rebake_identity.h')
        pak = (cu / 'MACHAB.PAK').read_bytes()
        mb = m['FZX_MACHINE_REBAKE_METADATA_BYTES']
        if (len(pak) != c['FZX_CLOSEUP_PACK_BYTES'] or fnv(pak) != c['FZX_CLOSEUP_PACK_HASH'] or
                mb + m['FZX_MACHINE_REBAKE_TEXTURE_BYTES'] != len(pak) or fnv(pak[:mb]) != m['FZX_MACHINE_REBAKE_METADATA_HASH'] or
                fnv(pak[mb:]) != m['FZX_MACHINE_REBAKE_TEXTURE_HASH']):
            print('mach3d_from_closeup: family %d pack does not match its identity' % f, file=sys.stderr); return 1
        outputs['MACH3D%02d.PAK' % f] = pak
        rows[f] = (len(pak), fnv(pak), m['FZX_MACHINE_REBAKE_METADATA_BYTES'], m['FZX_MACHINE_REBAKE_TEXTURE_BYTES'],
                   m['FZX_MACHINE_REBAKE_METADATA_HASH'], m['FZX_MACHINE_REBAKE_PALETTE_BYTES'], m['FZX_MACHINE_REBAKE_GOURAUD_BYTES'],
                   c['FZX_CLOSEUP_BODY_R'], c['FZX_CLOSEUP_BODY_G'], c['FZX_CLOSEUP_BODY_B'])
    h = ['/* Generated by tools/mach3d_from_closeup.py; derived from the owner\'s ROM: never commit. */',
         '#ifndef FZX_MACH3D_IDENTITY_H', '#define FZX_MACH3D_IDENTITY_H', '#include <stdint.h>',
         '/* Per stock family (index = family): pack bytes 0 = no pack. */',
         'typedef struct { uint32_t pack_bytes, pack_fnv, metadata_bytes, texel_bytes, metadata_fnv;',
         '                 uint16_t palette_bytes, gouraud_bytes; uint8_t body[3], present; } fzx_mach3d_identity_t;',
         '#define FZX_MACH3D_FAMILIES 30u',
         'static const fzx_mach3d_identity_t fzx_mach3d_identity[FZX_MACH3D_FAMILIES] = {']
    for f in sorted(rows):
        pb, pf, mb, tb, mf, pal, gou, r, g, b = rows[f]
        h.append('    [%d] = { %du, 0x%08Xu, %du, %du, 0x%08Xu, %du, %du, { %d, %d, %d }, 1 },' % (f, pb, pf, mb, tb, mf, pal, gou, r, g, b))
    h += ['};', '#endif', '']
    ident = '\n'.join(h).encode()
    out = a.output
    out.mkdir(parents=True, exist_ok=True)
    for n, d in outputs.items():
        (out / n).write_bytes(d)
    (out / 'mach3d_identity.h').write_bytes(ident)
    lines = ['# fzx generation receipt v1; regenerate, never edit',
             'generator %s mach3d_from_closeup.py' % sha(__file__)] + rec
    lines += ['output %s %s' % (hashlib.sha256(d).hexdigest(), n) for n, d in sorted(outputs.items())]
    lines.append('output %s mach3d_identity.h' % hashlib.sha256(ident).hexdigest())
    (out / 'mach3d.receipt').write_bytes(('\n'.join(lines) + '\n').encode())
    print('mach3d_scn: families %s' % ','.join(str(f) for f in sorted(rows)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
