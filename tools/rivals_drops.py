#!/usr/bin/env python3
"""Drop nodes for the rival field (SH2ZAM line-field-5 behave drop_mask; ENG_RIVAL_BEHAVE), from where the original's
CPU racers leave the track in reference GP runs.

    rivals_drops.py --pack RIVALS.PAK --length LINE_LENGTH_Q8 --out-txt drops.txt --out-h rivals_drops.h DIAG.bin...

DIAG.bin are fzx-gp-ref --diag outputs (one 88-byte record per racer and tick: int32 tick, id, stateFlags, shape,
unk_288, attacker, segment, lap, boostTimer, machineLod; float32 dist, lateral, ...). A fall starts on the first record
of a racer (not the player) with FALLING_OFF_TRACK (stateFlags bit 19). Each fall's lap distance marks the pack nodes
whose start lies within BEFORE units before it to AFTER units after it (overlapping ranges merge); in a tube the
range stays on the tube nodes, and out of a tube it reaches back to the tube's last node (the launch comes out of it).
The engine sets node flag 0x0200 on those nodes; the field's drops apply there only.
Outputs are derived from the owner's ROM: generated/ only, never committed.
"""
import argparse, struct

FALL = 1 << 19
REC = struct.Struct('<10i12f')
TUBE = (0x080, 0x0c0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--pack', required=True)
    ap.add_argument('--length', type=int, required=True, help='line length, Q8 (FZX_RIVALS_LINE_LENGTH)')
    ap.add_argument('--before', type=float, default=600.0)
    ap.add_argument('--after', type=float, default=300.0)
    ap.add_argument('--out-txt', required=True)
    ap.add_argument('--out-h', required=True)
    ap.add_argument('diag', nargs='+')
    a = ap.parse_args()
    b = open(a.pack, 'rb').read()
    if not b or len(b) % 48:
        raise SystemExit('pack is not nodes x 48')
    n = len(b) // 48
    nodes = [struct.unpack_from('>ihHHHI', b, 16 * i) for i in range(n)]
    start = [x[0] / 256.0 for x in nodes]
    shape = [x[4] & 0x1c0 for x in nodes]
    L = a.length / 256.0
    falls = []
    for p in a.diag:
        data = open(p, 'rb').read()
        seen = set()
        for off in range(0, len(data) - REC.size + 1, REC.size):
            r = REC.unpack_from(data, off)
            if r[1] == 0 or r[1] in seen or not r[2] & FALL:
                continue
            seen.add(r[1])
            falls.append(r[10] % L)
    marks = set()
    for d in falls:
        at = max(i for i in range(n) if start[i] <= d) if d >= start[0] else n - 1
        for i in range(n):
            gap = (start[i] - d + L / 2) % L - L / 2
            if -a.before <= gap <= a.after and (shape[i] in TUBE) == (shape[at] in TUBE):
                marks.add(i)
        if shape[at] not in TUBE:   # a launch: include the tube's last node before the fall
            j = at
            while j > 0 and shape[j] not in TUBE and at - j < 64:
                j -= 1
            if shape[j] in TUBE:
                marks.add(j)
    ranges = []
    for i in sorted(marks):
        if ranges and ranges[-1][1] == i - 1:
            ranges[-1][1] = i
        else:
            ranges.append([i, i])
    with open(a.out_txt, 'w') as o:
        o.write('# rivals_drops.py: %d falls in %d runs; node ranges (first last)\n' % (len(falls), len(a.diag)))
        for r in ranges:
            o.write('%d %d\n' % tuple(r))
    with open(a.out_h, 'w') as o:
        o.write('/* Generated by tools/rivals_drops.py from reference GP diagnostics (HOST, original code); derived from the'
                ' owner\'s ROM: regenerate, never edit, never commit. */\n')
        o.write('#ifndef FZX_RIVALS_DROPS_H\n#define FZX_RIVALS_DROPS_H\n#define FZX_RIVALS_DROP_COUNT %du\n#define FZX_RIVALS_DROP_MAX 8u\n' % len(ranges))
        o.write('static const uint16_t fzx_rivals_drops[FZX_RIVALS_DROP_MAX][2] = {%s};\n#endif\n' % (
            ', '.join('{%d, %d}' % tuple(r) for r in ranges[:8]) or '{0, 0}'))
    if len(ranges) > 8:
        raise SystemExit('more than 8 drop ranges')
    print('drops: %d falls, %d ranges %s' % (len(falls), len(ranges), ranges))


if __name__ == '__main__':
    main()
