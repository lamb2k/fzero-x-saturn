#!/usr/bin/env python3
"""Field config header for the Saturn rival field (E2 field lane), from a reference GP report.
Usage: rivals_field_header.py REFERENCE.json OUT.h [--course SLUG] [--speed-k K]
       rivals_field_header.py --classes NOVICE.json STANDARD.json EXPERT.json MASTER.json OUT_CLASS.h [--course SLUG] [--speed-k K]
--practice (with --classes; reports from fzx-gp-ref --mode practice): the finish column is the lap-2 pace of the reference itself, as a
3-lap-equivalent target: (its lap 1 + 2 x its reference lap 2) ms, and the target lap column is the reference's own lap 1. The engine stretches it over its endless field (engine_field.c).
The second form (ENG_RIVAL_CLASS, line-field-5 (d)) writes the four class row sets fzx_rivals_field_class[4][30][8]
(class = the source's gDifficulty, cpu.c's course * 4 + difficulty tables): one reference report per class, the same
seed and machines (the grid column may differ: Master's tier grid moves places), difficulties 0..3 in order. rivals_field.h is untouched.
The reference report comes from fzx-gp-ref (original code, 30 racers, HOST) and is derived from the
owner's ROM: the header goes to generated/rivals (git-ignored), never committed.
Per vehicle (id order, 0 = the player): grid, target lap ms, chase (255 none), max energy Q8,
aggression, character (stock family); the same rule as tools/rivals_e2_config.py (only racers chasing another CPU racer attack);
finish ms: the second-lap re-target (tools/rivals_finish.py, SH2ZAM line-field-2; 0 = none)."""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import rivals_finish  # noqa: E402
args = [a for a in sys.argv[1:] if not a.startswith('--')]
slug = sys.argv[sys.argv.index('--course') + 1] if '--course' in sys.argv else 'mute-city-1'
if '--course' in sys.argv: args.remove(slug)
speed_k = float(sys.argv[sys.argv.index('--speed-k') + 1]) if '--speed-k' in sys.argv else 0.0
if '--speed-k' in sys.argv: args.remove(sys.argv[sys.argv.index('--speed-k') + 1])


def field_rows(d):
    if '--practice' in sys.argv:
        finish = {}
        for r in d['racers']:
            e = r['lap_end_ticks']
            lap2 = e[1] - e[0] if e[0] > 0 and e[1] > 0 else 0
            finish[r['id']] = int(round((e[0] + 2 * lap2) * 1000 / 60)) if (lap2 and r['id'] and r['chase'] == 255) else 0
    else:
        finish = rivals_finish.targets(d, slug)
    caps = rivals_finish.chase_caps(d, slug, speed_k) if speed_k else {i: 0 for i in finish}
    rows = []
    for r in sorted(d['racers'], key=lambda r: r['id']):
        chase = r['chase']
        aggression = 38 if chase not in (0, 255) else 0
        lap_ms = r['target_lap_ms']
        if '--practice' in sys.argv and r['id'] and chase == 255 and r['lap_end_ticks'][0] > 0:
            lap_ms = int(round(r['lap_end_ticks'][0] * 1000 / 60.0))   # the reference's own lap 1 (its pace is not the row's target)
        rows.append((r['grid'], lap_ms, chase, int(round(r['max_energy'] * 256)), aggression, r['character'], finish[r['id']], caps[r['id']]))
    if [r['id'] for r in sorted(d['racers'], key=lambda r: r['id'])] != list(range(len(rows))):
        raise SystemExit('reference ids must run 0..n-1')
    return rows


if '--classes' in sys.argv:
    if len(args) != 5:
        raise SystemExit('--classes NOVICE.json STANDARD.json EXPERT.json MASTER.json OUT_CLASS.h')
    reps = [json.load(open(a)) for a in args[:4]]
    if [int(r['difficulty']) for r in reps] != [0, 1, 2, 3]:
        raise SystemExit('class reports must be difficulties 0, 1, 2, 3 in order')
    if len({int(r.get('seed', 1)) for r in reps}) != 1:
        raise SystemExit('class reports must share one seed')
    sets = [field_rows(r) for r in reps]
    # The grid may differ by class (the source's tier grid: Master moves places); the machines may not.
    if len({len(x) for x in sets}) != 1 or len({tuple(row[5] for row in x) for x in sets}) != 1:
        raise SystemExit('class reports must share one field (the same machines)')
    with open(args[4], 'w') as o:
        o.write('/* Generated by tools/rivals_field_header.py --classes from four reference GP reports (HOST, original code);'
                ' derived from the owner\'s ROM: regenerate, never edit, never commit. */\n')
        o.write('#ifndef FZX_RIVALS_FIELD_CLASS_H\n#define FZX_RIVALS_FIELD_CLASS_H\n')
        o.write('#define FZX_RIVALS_FIELD_CLASS_SEED %du\n' % int(reps[0].get('seed', 1)))
        o.write('/* [class: novice, standard, expert, master][vehicle] = the rivals_field.h row */\n')
        o.write('static const int32_t fzx_rivals_field_class[4][%d][8] = {\n' % len(sets[0]))
        for x in sets:
            o.write('  {\n')
            for r in x:
                o.write('    {%s},\n' % ', '.join('%d' % v for v in r))
            o.write('  },\n')
        o.write('};\n#endif\n')
    print('field class header: 4 classes x %d vehicles' % len(sets[0]))
    sys.exit(0)

d = json.load(open(args[0]))
rows = field_rows(d)
with open(args[1], 'w') as o:
    o.write('/* Generated by tools/rivals_field_header.py from a reference GP report (HOST, original code);'
            ' derived from the owner\'s ROM: regenerate, never edit, never commit. */\n')
    o.write('#ifndef FZX_RIVALS_FIELD_H\n#define FZX_RIVALS_FIELD_H\n#define FZX_RIVALS_FIELD_COUNT %du\n' % len(rows))
    o.write('#define FZX_RIVALS_FIELD_SEED %du\n' % int(d.get('seed', 1)))
    o.write('/* grid, target_lap_ms, chase (255 none), max_energy Q8, aggression, character, finish_ms, first-lap chase cap Q8 (0 none) */\n')
    o.write('static const int32_t fzx_rivals_field[%d][8] = {\n' % len(rows))
    for r in rows:
        o.write('    {%s},\n' % ', '.join('%d' % v for v in r))
    o.write('};\n#endif\n')
print('field header: %d vehicles' % len(rows))
