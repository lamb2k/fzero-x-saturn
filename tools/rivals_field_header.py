#!/usr/bin/env python3
"""Field config header for the Saturn rival field (E2 field lane), from a reference GP report.
Usage: rivals_field_header.py REFERENCE.json OUT.h
The reference report comes from fzx-gp-ref (original code, 30 racers, HOST) and is derived from the
owner's ROM: the header goes to generated/rivals (git-ignored), never committed.
Per vehicle (id order, 0 = the player): grid, target lap ms, chase (255 none), max energy Q8,
aggression, character (stock family); the same rule as tools/rivals_e2_config.py (only racers chasing another CPU racer attack)."""
import json, sys
d = json.load(open(sys.argv[1]))
rows = []
for r in sorted(d['racers'], key=lambda r: r['id']):
    chase = r['chase']
    aggression = 38 if chase not in (0, 255) else 0
    rows.append((r['grid'], r['target_lap_ms'], chase, int(round(r['max_energy'] * 256)), aggression, r['character']))
if [r['id'] for r in sorted(d['racers'], key=lambda r: r['id'])] != list(range(len(rows))):
    raise SystemExit('reference ids must run 0..n-1')
with open(sys.argv[2], 'w') as o:
    o.write('/* Generated by tools/rivals_field_header.py from a reference GP report (HOST, original code);'
            ' derived from the owner\'s ROM: regenerate, never edit, never commit. */\n')
    o.write('#ifndef FZX_RIVALS_FIELD_H\n#define FZX_RIVALS_FIELD_H\n#define FZX_RIVALS_FIELD_COUNT %du\n' % len(rows))
    o.write('#define FZX_RIVALS_FIELD_SEED %du\n' % int(d.get('seed', 1)))
    o.write('/* grid, target_lap_ms, chase (255 none), max_energy Q8, aggression, character */\n')
    o.write('static const int32_t fzx_rivals_field[%d][6] = {\n' % len(rows))
    for r in rows:
        o.write('    {%d, %d, %d, %d, %d, %d},\n' % r)
    o.write('};\n#endif\n')
print('field header: %d vehicles' % len(rows))
