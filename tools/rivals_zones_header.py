#!/usr/bin/env python3
"""Rival surface header for the engine (SH2ZAM line-field-4): the course's zones in line space and the
final-dash distance, from fzx-rivals --zones (ref/rivals_main.c).

    tools/rivals_zones_header.py ZONES.txt OUT.h

ZONES.txt has one zone per line, "start end lat_lo lat_hi kind" (Q8 distance and lateral, positive right;
kind 1 plate, 2 low grip, 3 rough, 4 recharge), sorted by start; ZONES.txt.dash holds the Q8 distance
into the final lap where the dash starts (0 none). Derived from the owner's ROM: generated/ only, never
committed.
"""
import sys
from pathlib import Path

MAX_ZONES = 32


def read(path):
    zones = []
    for line in Path(path).read_text().splitlines():
        if not line.strip():
            continue
        start, end, lo, hi, kind = (int(v) for v in line.split())
        if not (0 <= start < end and lo <= hi and 1 <= kind <= 4):
            raise SystemExit('%s: bad zone row' % path)
        zones.append((start, end, lo, hi, kind))
    if zones != sorted(zones, key=lambda z: z[0]):
        raise SystemExit('%s: zones are not sorted by start' % path)
    if len(zones) > MAX_ZONES:
        raise SystemExit('%s: more than %d zones' % (path, MAX_ZONES))
    dash = int(Path(str(path) + '.dash').read_text().split()[0])
    return zones, dash


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    zones, dash = read(sys.argv[1])
    rows = zones or [(0, 0, 0, 0, 0)]
    out = ['/* Generated by tools/rivals_zones_header.py from fzx-rivals --zones; derived from the owner\'s ROM: '
           'regenerate, never edit, never commit. */',
           '#ifndef FZX_RIVALS_ZONES_H', '#define FZX_RIVALS_ZONES_H',
           '#define FZX_RIVALS_ZONE_MAX %du' % MAX_ZONES,
           '#define FZX_RIVALS_ZONE_COUNT %du' % len(zones),
           '#define FZX_RIVALS_DASH_FROM %d' % dash,
           '/* start, end, lat_lo, lat_hi (Q8), kind (SH2Z_FIELD_ZONE_*) */',
           'static const int32_t fzx_rivals_zones[%d][5] = {' % len(rows)]
    out += ['    {%d, %d, %d, %d, %d},' % z for z in rows]
    out += ['};', '#endif', '']
    Path(sys.argv[2]).write_text('\n'.join(out))
    print('rival zones header: %d zones, dash from %d' % (len(zones), dash))


if __name__ == '__main__':
    main()
