#!/usr/bin/env python3
"""Offline track preparation (scenes lane, FZX_ROAD_PREP_BAKED): builds the HOST prepare
(tools/road_prep_host.c with src/fzx_road_stream_draw.c and the SH2ZAM portable kernels),
runs it on generated/road_bake's ROADLOD.PAK and ROADLTX.PAK, and writes
generated/road_prep/ROADPREP.PAK, road_prep_identity.h (sizes, counts and each table's
offset, length and FNV-1a, which the image checks as it reads) and road_prep.receipt.
The receipt lists the prepare's sources as generators, so a change to the prepare makes
the bake stale and the image build refuses it until this is run again.

Everything read or written comes from the owner's ROM: generated/ only, never committed.

    tools/road_prep.py --sh2zam SH2ZAM_CHECKOUT [--cc gcc]
"""
import argparse, hashlib, os, struct, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
G = ROOT / 'generated'
SOURCES = ('src/fzx_road_stream_draw.c', 'src/fzx_road_stream.c', 'src/fzx_road_pack.c',
           'src/fzx_view.c', 'src/fzx_view16.c', 'src/fzx_view16_center.c')
SH2ZAM_UNITS = ('sh2zam.c', 'sh2zam_view.c', 'sh2zam_view_round.c', 'sh2zam_view_guard_src.c',
                'sh2zam_view_center.c', 'sh2zam_view_guard_src_center.c', 'sh2zam_view_merge_tier.c',
                'sh2zam_shade.c', 'sh2zam_shade_fused.c', 'sh2zam_view_rails.c', 'sh2zam_divu.c')
# The engine image's road options that shape the prepare (saturn/engine/Makefile).
DEFINES = ('-DFZX_ENGINE=1', '-DFZX_ROAD_STREAM_NATIVE_LAYOUT=1', '-DFZX_RS_PACK_PATH=0', '-DFZX_ROAD_STREAM_EMIT=1',
           '-DFZX_RS_PACKET_PATH=0', '-DFZX_ROAD_STREAM_BUDGET=1', '-DFZX_ROAD_STREAM_CLUSTERS=0',
           '-DFZX_SOURCE_ROAD=1', '-DFZX_SOURCE_ROAD_STREAM=1', '-DFZX_ROAD_LOD=1', '-DSH2Z_FORCE_PORTABLE=1')
GENERATORS = ('tools/road_prep.py', 'tools/road_prep_host.c') + SOURCES


def fnv(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--sh2zam', required=True, type=Path)
    ap.add_argument('--cc', default='gcc')
    ap.add_argument('--output', type=Path, default=G / 'road_prep')
    ap.add_argument('--bake', type=Path, default=G / 'road_bake', help='road_bake.py output for this course')
    ap.add_argument('--texture-limit', type=int, help='the track texture budget the bake used (road_bake.py --texture-limit)')
    a = ap.parse_args()
    bake = a.bake.resolve()
    defines = [*DEFINES, *(['-DFZX_ROAD_STREAM_TEXTURE_LIMIT=%du' % a.texture_limit] if a.texture_limit else [])]
    subprocess.run(['sh', str(ROOT / 'tools/check_receipt.sh'), str(bake / 'road_bake.receipt')], check=True, stdout=subprocess.DEVNULL)
    lib = a.sh2zam
    with tempfile.TemporaryDirectory() as t:
        exe = Path(t) / 'road_prep_host'
        args = [a.cc, '-std=c11', '-O2', '-Wall', '-Wextra', '-Werror', *defines,
                '-I' + str(ROOT / 'include'), '-I' + str(ROOT / 'src'), '-I' + str(ROOT / 'ref'), '-I' + str(bake),
                '-I' + str(lib / 'saturn/include'), str(ROOT / 'tools/road_prep_host.c'),
                *[str(ROOT / s) for s in SOURCES], *[str(lib / 'saturn/src' / u) for u in SH2ZAM_UNITS], '-o', str(exe)]
        subprocess.run(args, check=True)
        out = a.output
        out.mkdir(parents=True, exist_ok=True)
        pak = out / 'ROADPREP.PAK'
        subprocess.run([str(exe), str(bake / 'ROADLOD.PAK'), str(bake / 'ROADLTX.PAK'), str(pak)], check=True)
    data = pak.read_bytes()
    if data[:8] != b'FZXRPP01' or struct.unpack_from('>I', data, 12)[0] != len(data):
        print('road_prep: bad output', file=sys.stderr); return 1
    npos, nq, nc, ni, ns = struct.unpack_from('>5I', data, 24)
    names = ('NUNIT', 'NPOS', 'NQUADS', 'NSPANS', 'NCHUNKS', 'IMAGES')
    h = ['/* Generated by tools/road_prep.py; derived from the owner\'s ROM: never commit. */',
         '#ifndef FZX_ROAD_PREP_IDENTITY_H', '#define FZX_ROAD_PREP_IDENTITY_H',
         '#define FZX_ROAD_PREP_BYTES %du' % len(data), '#define FZX_ROAD_PREP_FILE_HASH 0x%08Xu' % fnv(data),
         '#define FZX_ROAD_PREP_LOD_HASH 0x%08Xu' % struct.unpack_from('>I', data, 16)[0],
         '#define FZX_ROAD_PREP_LTX_HASH 0x%08Xu' % struct.unpack_from('>I', data, 20)[0],
         '#define FZX_ROAD_PREP_NPOS_COUNT %du' % npos, '#define FZX_ROAD_PREP_QUADS %du' % nq,
         '#define FZX_ROAD_PREP_CHUNKS %du' % nc, '#define FZX_ROAD_PREP_IMAGES %du' % ni, '#define FZX_ROAD_PREP_STRIPS %du' % ns]
    for i, n in enumerate(names):
        at, ln = struct.unpack_from('>II', data, 44 + 8 * i)
        ln4 = (ln + 3) & ~3   # the image reads whole words (the file pads each table to 4)
        h += ['#define FZX_ROAD_PREP_%s_AT %du' % (n, at), '#define FZX_ROAD_PREP_%s_BYTES %du' % (n, ln4),
              '#define FZX_ROAD_PREP_%s_HASH 0x%08Xu' % (n, fnv(data[at:at + ln4]))]
    h += ['#endif', '']
    ident = '\n'.join(h).encode()
    (out / 'road_prep_identity.h').write_bytes(ident)
    rec = ['# fzx generation receipt v1; regenerate, never edit']
    rec += ['generator %s %s' % (sha(ROOT / g), os.path.relpath(ROOT / g, ROOT / 'tools').replace('\\', '/')) for g in GENERATORS]
    rec += ['generator %s %s' % (sha(bake / 'road_bake.receipt'), os.path.relpath(bake / 'road_bake.receipt', ROOT / 'tools').replace('\\', '/')),
            'input %s ROADLOD.PAK' % sha(bake / 'ROADLOD.PAK'), 'input %s ROADLTX.PAK' % sha(bake / 'ROADLTX.PAK'),
            'output %s ROADPREP.PAK' % hashlib.sha256(data).hexdigest(),
            'output %s road_prep_identity.h' % hashlib.sha256(ident).hexdigest()]
    (out / 'road_prep.receipt').write_bytes(('\n'.join(rec) + '\n').encode())
    print('road prep: %d bytes (%d positions, %d quads, %d chunks, %d images)' % (len(data), npos, nq, nc, ni))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
