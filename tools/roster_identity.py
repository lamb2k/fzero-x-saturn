#!/usr/bin/env python3
"""Identity header for a private rotation-sprite roster pack (E2 field lane, E2_ROSTER).
Usage: roster_identity.py ROSTER.PAK EXPECTED_SHA256 OUT.h
Refuses (exit 1) unless the pack's SHA-256 is the expected one. The pack and the header are derived
from the owner's ROM: generated/roster only, never committed. The Saturn checks the FNV-1a hash
written here over the whole file at load (fzx_texture_cd_load) and refuses a mismatch."""
import hashlib, struct, sys
pak, expected, out = sys.argv[1:4]
b = open(pak, 'rb').read()
sha = hashlib.sha256(b).hexdigest()
if sha != expected.lower():
    print('roster: SHA-256 mismatch: refused', file=sys.stderr); sys.exit(1)
h = 2166136261
for x in b: h = ((h ^ x) * 16777619) & 0xffffffff
ent = struct.Struct('>8s4sIIIHHI')
n = 0
while n * 32 + 32 <= len(b):
    k, p, o, ln, fnv, v, r, z = ent.unpack_from(b, n * 32)
    if v != 0x101 or o % 2048 or o + ln > len(b): break
    n += 1
if len(b) % 4: print('roster: size is not a multiple of 4', file=sys.stderr); sys.exit(1)
with open(out, 'w') as o:
    o.write('/* Generated by tools/roster_identity.py from a private roster pack; derived from the owner\'s ROM:'
            ' never commit. */\n#ifndef FZX_ROSTER_IDENTITY_H\n#define FZX_ROSTER_IDENTITY_H\n')
    o.write('#define FZX_ROSTER_BYTES %du\n#define FZX_ROSTER_HASH 0x%08xu\n#define FZX_ROSTER_SETS %du\n' % (len(b), h, n))
    o.write('#define FZX_ROSTER_SHA256 "%s"\n#endif\n' % sha)
print('roster identity: %d sets, %d bytes' % (n, len(b)))
