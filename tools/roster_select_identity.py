#!/usr/bin/env python3
"""Identity header for the engine's selective roster load (scenes lane, ENG_ROSTER).

Reads the RSZ1 compressed roster pack (tools/racer_stream.py pack, from Codex's RSP1 1.1
roster pack) and writes generated/roster/rosterz_identity.h: the pack's size, the code-length
block, and per set its key, profile, block offset and length (the set's header, cell table,
CLUTs, stream table, alias map and streams, contiguous), the FNV-1a of that block (checked as
the block is read), the header and stream table offsets inside the block, and the FNV-1a of
the raw RSP1 1.1 set (checked when a whole set is inflated).

Refuses (exit 1) unless the source roster's SHA-256 is the expected one, and records the RSZ1
pack's own SHA-256 in the header and the receipt. Everything read or written here derives from
the owner's ROM: generated/roster only, never committed.

    tools/roster_select_identity.py ROSTER.PAK EXPECTED_SHA256 ROSTERZ.PAK OUT_DIR
"""
import hashlib, os, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fnv(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h


def main():
    if len(sys.argv) != 5:
        print(__doc__, file=sys.stderr); return 2
    roster, expected, rsz, out = sys.argv[1:5]
    src = open(roster, 'rb').read()
    if hashlib.sha256(src).hexdigest() != expected.lower():
        print('roster: SHA-256 mismatch: refused', file=sys.stderr); return 1
    z = open(rsz, 'rb').read()
    if z[:4] != b'RSZ1':
        print('rsz: not an RSZ1 pack', file=sys.stderr); return 1
    version, count = struct.unpack_from('>HH', z, 4)
    dir_at = 8 + 16 * 30
    while dir_at % 8:
        dir_at += 1
    ent = struct.Struct('>8s4sIIIII')
    raw_entry = struct.Struct('>8s4sIIIHHI')
    raw_sets = {}
    for offset in range(0, len(src) - raw_entry.size + 1, raw_entry.size):
        key, prof, at, size, raw_hash, raw_version, framing, _ = raw_entry.unpack_from(src, offset)
        if raw_version != 0x101:
            break
        if framing == 2:
            raw_sets[(key, prof)] = raw_hash
    rows = []
    for i in range(count):
        key, prof, h_at, hb, st_at, sb, raw_fnv = ent.unpack_from(z, dir_at + i * ent.size)
        if raw_sets.pop((key, prof), None) != raw_fnv:
            print('roster: compressed set does not match source roster', file=sys.stderr); return 1
        end = st_at + sb
        end = (end + 7) & ~7
        block = z[h_at:end]
        rows.append((key, prof, h_at, end - h_at, fnv(block), hb, st_at - h_at, raw_fnv))
    if raw_sets:
        print('roster: compressed directory missing source sets', file=sys.stderr); return 1
    lens = z[8:8 + 16 * 30]
    o = Path(out)
    o.mkdir(parents=True, exist_ok=True)
    sha = hashlib.sha256(z).hexdigest()
    h = ['/* Generated by tools/roster_select_identity.py; derived from the owner\'s ROM: never commit. */',
         '#ifndef FZX_ROSTERZ_IDENTITY_H', '#define FZX_ROSTERZ_IDENTITY_H', '#include <stdint.h>',
         '#define FZX_RZ_BYTES %du' % len(z), '#define FZX_RZ_SETS %du' % count,
         '#define FZX_RZ_LENS_AT 8u', '#define FZX_RZ_LENS_BYTES 480u', '#define FZX_RZ_LENS_FNV 0x%08Xu' % fnv(lens),
         '#define FZX_RZ_SHA256 "%s"' % sha,
         'typedef struct { char key[8]; char prof[4]; uint32_t at, bytes, fnv, header_bytes, table_at, raw_fnv; } fzx_rz_set_t;',
         'static const fzx_rz_set_t fzx_rz_sets[FZX_RZ_SETS] = {']
    for key, prof, at, n, f, hb, ta, rf in rows:
        k = ', '.join('%d' % c for c in key)
        p = ', '.join('%d' % c for c in prof)
        h.append('    { { %s }, { %s }, %du, %du, 0x%08Xu, %du, %du, 0x%08Xu },' % (k, p, at, n, f, hb, ta, rf))
    h += ['};', '#endif', '']
    data = '\n'.join(h).encode()
    (o / 'rosterz_identity.h').write_bytes(data)
    rec = ['# fzx generation receipt v1; regenerate, never edit',
           'generator %s roster_select_identity.py' % hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
           'generator %s racer_stream.py' % hashlib.sha256((ROOT / 'tools/racer_stream.py').read_bytes()).hexdigest(),
           'input %s ROSTER.PAK' % hashlib.sha256(src).hexdigest(),
           'output %s ROSTERZ.PAK' % sha,
           'output %s rosterz_identity.h' % hashlib.sha256(data).hexdigest()]
    (o / 'rosterz.receipt').write_bytes(('\n'.join(rec) + '\n').encode())
    print('rosterz identity: %d sets, %d bytes, sha256 %s' % (count, len(z), sha))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
